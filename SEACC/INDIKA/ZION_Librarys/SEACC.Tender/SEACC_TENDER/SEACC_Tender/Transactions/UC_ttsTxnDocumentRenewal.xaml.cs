        private void Btn_Save_Click(object sender, RoutedEventArgs e)
        {
            if (SEACC_Form.CheckPermisshion_ToSave(SEACC_Form.IsUpdateMode))
            {
                if (CheckValidity())
                {
                    string sDocID = "";
                    try
                    {
                        if (SEACC_Form.IsUpdateMode)
                        {
                            #region Update
                            tbl_ttsTenderDocumentRenewals oldDetail = tbl_ttsTenderDocumentRenewals.Select(txtDocRenewalID.Text);
                            if (oldDetail != null)
                            {
                                tbl_ttsTenderDocumentRenewals oDetails = new tbl_ttsTenderDocumentRenewals(txtDocRenewalID.Text, txtItemCode.Tag.ToString(), txtDocCode.Tag.ToString(), int.Parse(txtRenewalType1.Tag.ToString()), 0, dtpExpiryDate.GetDateTime().Date, txtRemarks.Text, int.Parse(txtReminderDays.Text), cmbFrequence.GetSelectedIndex(), dtpTime.GetDateTime().Date, true, false);
                                oDetails.Update();
                                SEACCMessageBox.Show(MessegeBoxType.Successfully_Updated);
                            }
                            #endregion
                        }
                        else
                        {
                            #region Insert
                            if (SEACC_Form.isAutoGenaratedCode)
                                sDocID = txtDocRenewalID.Text = SEACC_Form.getAutoGeneratedCode();

                            tbl_ttsTenderDocumentRenewals oDetail = new tbl_ttsTenderDocumentRenewals(txtDocRenewalID.Text, txtItemCode.Tag.ToString(), txtDocCode.Tag.ToString(), int.Parse(txtRenewalType1.Tag.ToString()), 0, dtpExpiryDate.GetDateTime().Date, txtRemarks.Text, int.Parse(txtReminderDays.Text), cmbFrequence.GetSelectedIndex(), dtpTime.GetDateTime(), true, false);
                            oDetail.Insert();
                            Attachments.Insert(txtDocRenewalID.Text);
                            SEACCMessageBox.Show(MessegeBoxType.Successfully_Created);
                            #endregion
                        }
                    }
                    catch (Exception Ex)
                    {
                        SEACCExeption.Show(Ex);
                    }
                    finally
                    {
                        sDocID = txtDocRenewalID.Text;
                        ClearFields();
                        FillDetails(sDocID);
                    }
                }

            }
        }

