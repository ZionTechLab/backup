        private bool CheckValidity_EmptyFields()
        {
            string strMessage = "";
            bool bStatus = true;

            if (!clsValidation.Validate_EmptyValue(txtItemCode, ref strMessage))
                bStatus = false;
            else if (!clsValidation.Validate_EmptyValue(txtDocCode, ref strMessage))
                bStatus = false;
            else if (!clsValidation.Validate_EmptyValue(txtRenewalType1, ref strMessage))
                bStatus = false;
            else if (!clsValidation.Validate_EmptyValue(cmbFrequence))
                bStatus = false;

            if (bStatus == false)
                SEACCMessageBox.Show("Fields cannot be Empty", strMessage, MessageBoxButton.OK);

            return bStatus;
        }
        private bool CheckGridvalidity()
        {
            bool bStatus = true;
            if (Attachments.dt2.Rows.Count <= 0)
            {
                SEACCMessageBox.Show("Please select file to upload..", "Upload files", MessageBoxButton.OK);
                bStatus = false;
            }
            return bStatus;
        }
