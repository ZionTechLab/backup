        #region Refresh Grid
        private void RefreshGrid()
        {
            try
            {
                dgr_Main.dt.Clear();
                foreach (tbl_zCustomerClass item in tbl_zCustomerClass.SelectAll().Where(p => p.CustomerClass_ID != "default"))
                {
                    dgr_Main.dt.Rows.Add(item.CustomerClass_ID, item.ClassName);
                }
                dgr_Main.RefreshGrid();
            }
            catch (Exception ex)
            {
                SEACCMessageBox.Show("Error", ex.Message, MessageBoxButton.OK);
            }
        }
        #endregion

        #region Clear Fields
        private void ClearFields()
        {
            SEACC_Form.IsUpdateMode = false;
            cls_Formater.SetEnableDisable_PrimaryKeyLabelTextBox(txtCustomerClassID, true, false, false);
            cls_Formater.SetEnableDisable_LableTextbox(txtCustomerClassName, true, false, false);

            txtCustomerClassID.Text = "";
            txtCustomerClassName.Text = "";

            txtCustomerClassID.Tag = null;

            if (SEACC_Form.isAutoGenaratedCode)
            {
                txtCustomerClassID.setReadOnlyStatus(true);
                txtCustomerClassID.Text = "<Auto Generate>";
            }
            else
                txtCustomerClassID.setReadOnlyStatus(false);
        }
        #endregion

        #region Action Buttons
        void btn_Save_Click(object sender, RoutedEventArgs e)
        {
            if (CheckValidity())
            {
                try
                {
                    if (SEACC_Form.IsUpdateMode)
                    {
                        if (SEACC_Form.CheckPermisshion_ToUpdate())
                        {
                            tbl_zCustomerClass OldClass = tbl_zCustomerClass.Select(txtCustomerClassID.Text);
                            if (OldClass != null)
                            {
                                tbl_zCustomerClass oClass = new tbl_zCustomerClass(txtCustomerClassID.Text, txtCustomerClassName.Text);
                                oClass.Update();
                                SEACCMessageBox.Show(MessegeBoxType.Successfully_Updated);
                            }
                        }
                    }
                    else
                    {
                        if (SEACC_Form.isAutoGenaratedCode)
                            txtCustomerClassID.Text = SEACC_Form.getAutoGeneratedCode();
                        tbl_zCustomerClass nClass = new tbl_zCustomerClass(txtCustomerClassID.Text, txtCustomerClassName.Text);
                        nClass.Insert();
                        SEACCMessageBox.Show(MessegeBoxType.Successfully_Created);
                    }
                }
                catch (Exception ex)
                {
                    SEACCExeption.Show(ex);
                }
                finally
                {
                    ClearFields();
                    RefreshGrid();
                }
            }
        }

