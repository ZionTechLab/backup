        #region Methord for Settle current Document
        private bool SettleLoanInFlow(tbl_scsLoanOut oLoanOutForLoanIn, tbl_scsLoanIn oLoanIn, decimal dSettleQty, decimal dUnitPrice, bool isWeight, bool isPriceAllocatioon, bool isLoanInBase)
        {
            #region Setting up Allocation Code
            if (txtAllocationID.Text != "")
            {
                if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                    txtAllocationID.Text = clsAutocode.getAutoGeneratedCode(sFormConfigCode);
            }
            frm_scsLoan.sAllocationID = txtAllocationID.Text;
            #endregion

            #region Settle Loan
            if (true)
            {
                bool isOk = true;
                if (oLoanOutForLoanIn.TotalWeight > oLoanIn.TotalWeight)
                {
                    //  MessageBox.Show("Over Allocation Than LoanOut Not Allow....!", clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Error);
                    // isOk = false;
                }
                else if (oLoanOutForLoanIn.TotalWeight < oLoanIn.TotalWeight)
                {

                }
                if (!isPriceAllocatioon)
                    oLoanIn.SeattleAmount += oLoanIn.TotalWeight != 0 ? oLoanIn.TotalWeight - dSettleQty : oLoanIn.TotalQty - dSettleQty;
                else
                    oLoanIn.SeattleAmount += oLoanIn.TotalWeightPrice != 0 ? oLoanIn.TotalWeightPrice - dUnitPrice : oLoanIn.TotalUnitPrice - dUnitPrice;

                oLoanIn.Update();

                //oLoanOutForLoanIn.IsSeattled = chkisSettle.Checked;
                oLoanOutForLoanIn.SeattleAmount = !isPriceAllocatioon ? dSettleQty : dUnitPrice;
                oLoanOutForLoanIn.Update();

                tbl_scsLoanSettle oLoanSettle = new tbl_scsLoanSettle(txtAllocationID.Text, oLoanIn.LoanIn_ID, oLoanOutForLoanIn.LoanOut_ID, oLoanOutForLoanIn.TotalQty, oLoanOutForLoanIn.TotalWeight, oLoanOutForLoanIn.TotalUnitPrice, oLoanOutForLoanIn.TotalWeightPrice, dtmAllocationDate.Value.Date, isPriceAllocatioon, isLoanInBase);
                oLoanSettle.Insert();
                return isOk;
            }

            #endregion
        }
