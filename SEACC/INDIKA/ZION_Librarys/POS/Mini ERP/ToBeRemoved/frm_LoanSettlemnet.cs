                                            {
                                                oSettleLoanIN.IsSeattled = chkisSettle.Checked;
                                                oSettleLoanIN.Update();
                                            }
                                            tbl_scsLoanOut oSettleLoanOut = tbl_scsLoanOut.Select(oSettle.LoanOut_ID);
                                            if (oSettleLoanOut != null && oSettleLoanOut.LoanOut_ID != "default")
                                            {
                                                oSettleLoanOut.IsSeattled = chkisSettle.Checked;
                                                oSettleLoanOut.Update();
                                            }
                                        }

                                    }
                                }
                                #endregion

                            }
                            #endregion
                        }
                        #endregion

                        #region Loan Out Base
                        else
                        {
                            string[] oLonId = frm_scsLoan.sLoanInID.ToString().Split(',');
                            oLoanOut = tbl_scsLoanOut.Select(frm_scsLoan.sLonOutID);

