                            {
                                foreach (string sLonID in saLonId)
                                {
                                    #region Settle Loan In
                                    decimal dSettleQty = 0;
                                    tbl_scsLoanOut oLoanOutForLoanIn = tbl_scsLoanOut.Select(sLonID);
                                    if (oLoanOutForLoanIn != null) // &&)
                                    {
                                        if (!oLoanOutForLoanIn.IsDeleted && !oLoanIn.IsDeleted)
                                        {
                                            if (!oLoanIn.IsSeattled)
                                            {
                                                if (oLoanOutForLoanIn.IsWeightCalculation == oLoanIn.IsWeightCalculation)//oLoanOutForLoanIn.IsWeightCalculation == oLoanIn.IsWeightCalculation
                                                {
                                                    if (!bIsPriceAllocatioon)
                                                        dSettleQty = oLoanOutForLoanIn.TotalWeight != 0 ? oLoanOutForLoanIn.TotalWeight : oLoanOutForLoanIn.TotalQty;
                                                    else
                                                        dUnitPriceSettle = oLoanOutForLoanIn.TotalWeightPrice != 0 ? oLoanOutForLoanIn.TotalWeightPrice : oLoanOutForLoanIn.TotalUnitPrice;

                                                    #region Settle Document
                                                    if (SettleLoanInFlow(oLoanOutForLoanIn, oLoanIn, dSettleQty, dUnitPriceSettle, oLoanOutForLoanIn.IsWeightCalculation, bIsPriceAllocatioon, true))
