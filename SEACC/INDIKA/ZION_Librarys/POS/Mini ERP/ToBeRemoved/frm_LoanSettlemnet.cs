                                                if (oLoanInForLoanOut.IsWeightCalculation == oLoanOut.IsWeightCalculation)//oLoanInForLoanOut.IsWeightCalculation == oLoanOut.IsWeightCalculation
                                                {
                                                    if (!bIsPriceAllocatioon)
                                                        dSettleQty = oLoanInForLoanOut.TotalWeight != 0 ? oLoanInForLoanOut.TotalWeight : oLoanInForLoanOut.TotalQty;
                                                    else
                                                        dUnitPriceSettle = oLoanInForLoanOut.TotalWeightPrice != 0 ? oLoanInForLoanOut.TotalWeightPrice : oLoanInForLoanOut.TotalUnitPrice;


