                                {
                                    string[] saLonId_Temp = frm_scsLoan.sLonOutIDAll.ToString().Split(',');
                                    foreach (string sLonID in saLonId_Temp)
                                    {
                                        foreach (tbl_scsLoanSettle oSettle in tbl_scsLoanSettle.SelectAllByLoanOut_ID(sLonID).Where(p => p.LoanIn_ID != "default"))
                                        {
                                            tbl_scsLoanIn oSettleLoanIN = tbl_scsLoanIn.Select(oSettle.LoanIn_ID);
