        #region Btn New
        private void btnNew_Click(object sender, EventArgs e)
        {
            ClearFields();
        }
        #endregion

        #region Btn Delete
        private void btnDelete_Click(object sender, EventArgs e)
        {
            try
            {
                if (txtSpecificationID.TextLength > 0)
                {
                    if (clsSecurity.PermissionToDelete(clsSecurity.UserIDLoged, iFormID))
                    {
                        //delete one record
                        Cursor = Cursors.WaitCursor;
                        tbl_zItemSpecification detail = tbl_zItemSpecification.Select(txtSpecificationID.Text.Trim());
                        if (detail != null)
                        {
                            detail.Delete();
                            clsHelpMethods.InsertTransactionHistory(iFormID, txtSpecificationID.Text, TxnActivity.Cancel);
                        }

                        Cursor = Cursors.Default;
                        MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.DeleteDone), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                        ClearFields();
                        RefreshGrid();
                    }
                    else //if no permission to delete
                    {
                        MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.PermissionToDelete), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                Cursor = Cursors.Default;
                SEACCException.Show(ex);
            }
        }
        #endregion

        #region Btn Save
        private void btnSave_Click(object sender, EventArgs e)
        {
            if (CheckValidity())
            {
                if (CheckNumberValidity())
                {
                   if (clsSecurity.PermissionToSave(clsSecurity.UserIDLoged, iFormID, IsUpdate))
                    {
                        try
                        {
                            Cursor = Cursors.WaitCursor;
                            if (txtSpecificationID.TextLength > 0)
                            {
                                if (IsUpdate)  //update records
                                {
                               
                                    tbl_zItemSpecification oldRecord = tbl_zItemSpecification.Select(txtSpecificationID.Text.Trim());
                                    if (oldRecord != null)
                                    {
                                        tbl_zItemSpecification detail = new tbl_zItemSpecification(txtSpecificationID.Text.Trim(), txtCategoryName.Tag.ToString(), txtSpecificationName.Text.Trim().ToUpper());
                                        detail.Update();
                                        clsHelpMethods.InsertTransactionHistory(iFormID, txtSpecificationID.Text, TxnActivity.Update);
                                        MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.ModifyDone), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                                    }
                                }
                                else  //insert records
                                {
                                    if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                                        txtSpecificationID.Text = clsAutocode.getAutoGeneratedCode(sFormConfigCode);

                                    //Inquiry Header
                                    tbl_zItemSpecification detail = new tbl_zItemSpecification(txtSpecificationID.Text.Trim(), txtCategoryName.Tag.ToString(),txtSpecificationName.Text.Trim().ToUpper());                               
                                    detail.Insert();
                                    clsHelpMethods.InsertTransactionHistory(iFormID, txtSpecificationID.Text, TxnActivity.Insert);
                                    MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.SaveDone), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                                }
                            }
                            else
                            {
                                MessageBox.Show("Item Specification " + clsFormatter.GetMessageFrom(MessageType.IDIsEmpty), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                            }
                        }
                        catch (Exception ex)
                        {
                            clsValidate.WriteErrorLog("", iFormID,ex);
                            SEACCException.Show(ex);
                        }
                        finally
                        {
                            Cursor = Cursors.Default;
                            ClearFields();
                            RefreshGrid();
                        }
                    }
                }
            }
        }
        #endregion


        #region Datagrid Format
        private void CusDataGridViewFormat()
        {
            clsFormatter.ApplyGridFormat(dgvDetail);
        }
        #endregion

        #region Clear Fields
        private void ClearFields()
        {
            //set the flag and enble the id
            IsUpdate = false;
            clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtSpecificationID, true);
            clsCommon.SetEnableDisable_NormalLabel(lblSupplierTypeID, true);

            txtCategoryName.Tag = null;
            txtCategoryName.Clear();
            txtSpecificationName.Clear();

            if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                txtSpecificationID.Text = "<Auto Generate>";
            else
                txtSpecificationID.Clear();
              

            if (txtSpecificationID.Enabled)
            {
                txtSpecificationID.SelectAll();
                txtSpecificationID.Focus();
            }

        }
        #endregion

        #region Refresh Grid
        private void RefreshGrid()
        {
            try
            {
                int iRow;
                dgvDetail.Rows.Clear();
                List<tbl_zItemSpecification> details = tbl_zItemSpecification.SelectAll();
                foreach (tbl_zItemSpecification detail in details)
                {
                    if (detail.ItemSepcification_ID.Trim() != "default")
                    {
                        dgvDetail.Rows.Add();
                        iRow = dgvDetail.Rows.Count - 1;
                        dgvDetail["SpecificationID", iRow].Value = detail.ItemSepcification_ID;
                        dgvDetail["SpecificationName", iRow].Value = detail.SepcificationName;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion

        #region Fill Details
        private void FillDetails(string sID)
        {
            try
            {
                if (sID.Length > 0)
                {
                    tbl_zItemSpecification detail = tbl_zItemSpecification.Select(sID);
                    if (detail != null)
                    {
                        //set the update flag and Locked
                        IsUpdate = true;
                        clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtSpecificationID, false);
                        clsCommon.SetEnableDisable_NormalLabel(lblSupplierTypeID, false);

                        //asign values
                        txtCategoryName.Tag = detail.ItemCategory_ID;
                        txtCategoryName.Text = clsCommon.GetForeignKeyValue(clsGenaralName.getName_ItemCategory(detail.ItemCategory_ID));
                        txtSpecificationID.Text = detail.ItemSepcification_ID;
                        txtSpecificationName.Text = detail.SepcificationName;

                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion


        #region Check Validity
        private bool CheckValidity()
        {
            string strMessage = "";
            bool bStatus = true;

            if (txtCategoryName.TextLength == 0)
            {
                strMessage += "\n" + "ItemClass Name ";
                bStatus = false;
            }
            if (txtSpecificationName.TextLength == 0)
            {
                strMessage += "\n" + "ItemType Name ";
                bStatus = false;
            }
            if (bStatus == false)
            {
                MessageBox.Show(clsFormatter.getCommonStatusStripMessage(StatusStripMessageTypes.WhenInsert, strMessage), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            return bStatus;
        }
        private bool CheckNumberValidity()
        {
            string strMessage = "";
            bool bStatus = true;

            try
            {


            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
            if (bStatus == false)
            {
                MessageBox.Show(clsFormatter.getCommonStatusStripMessage(StatusStripMessageTypes.WhenInserNumber, strMessage), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            return bStatus;
        }
