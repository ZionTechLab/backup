        #region Form Load
        public frm_mtrItemSpecification()
        {
            sFormConfigCode = clsAutocode.getFormConfigCode(FormName.ZItemSpecification);
            iFormID = clsSecurity.getFormID(FormName.ZItemSpecification);
            if (!clsSecurity.PermissionToRead(clsSecurity.UserIDLoged, iFormID))
            {
                bNoAccess = true;
            }
            InitializeComponent();
        }
        private void frm_mtrMachineType_Load(object sender, EventArgs e)
        {
            //add data to the datagrid and format
            RefreshGrid();
            CusDataGridViewFormat();
            ClearFields();
        }
