        #region Refresh Grid
        private void RefreshGrid()
        {
            try
            {
                int iRow;
                dgvDetail.Rows.Clear();

                List<tbl_securityConfigStatus> details = tbl_securityConfigStatus.SelectAll();
                foreach (tbl_securityConfigStatus detail in details)
                {
                    if (detail.ValueID != 0)
                    {
                        dgvDetail.Rows.Add();
                        iRow = dgvDetail.Rows.Count - 1;
                        dgvDetail["StatusID", iRow].Value = detail.ValueID;
                        dgvDetail["StatusName", iRow].Value = detail.ValueName;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion

        #region Clear Fields
        private void ClearFields()
        {
            //set the flag and enable the id
            IsUpdate = false;
            clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtStatusID, true);
            clsCommon.SetEnableDisable_NormalLabel(lblTypeValueID, true);


            txtTypeStatusName.Clear();
            rdbFalse.Checked = false;
            rdbTrue.Checked = false;
            txtConfigTypeStatusID.Clear();

            if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                txtStatusID.Text = "<Auto Generate>";
            else
                txtStatusID.Clear();
            if (txtStatusID.Enabled)
            {
                txtStatusID.SelectAll();
                txtStatusID.Focus();
            }
        }
        #endregion

        #region Fill Details

        private void FillDetails(string sID)
        {
            try
            {
                int iSID;
                if (sID.Length > 0)
                {
                    int.TryParse(sID,out iSID);
                    tbl_securityConfigStatus detail = tbl_securityConfigStatus.Select(iSID);
                    if (detail != null)
                    {
                        //set the update flag and Locked
                        IsUpdate = true;
                        clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtStatusID, false);
                        clsCommon.SetEnableDisable_NormalLabel(lblTypeValueID, false);

                        // Assign values
                        txtStatusID.Text =Convert.ToString( detail.ValueID);
                        txtConfigTypeStatusID.Text = detail.ConfigTypeStatus_ID;
                        txtTypeStatusName.Text = detail.ValueName;
                      
                        if (detail.ConfigValue)
                        {
                            rdbTrue.Checked = true;
                        }
                        else if(!detail.ConfigValue)
                        {
                            rdbFalse.Checked = true;
                        }
                       

                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }

