        #region Check Validity
        private bool CheckValidity()
        {
            string strMassage = "";
            bool bStatus = true;

            if (txtTypeStatusName.Text.Trim().Length == 0)
            {
                strMassage = strMassage + "\n " + "Type Status";
                //  string.Concat(strMassage, "\n ", "Type Status");
                bStatus = false;
            }

            if (!rdbTrue.Checked && !rdbFalse.Checked)
            {
                strMassage += "\n " + "status";
                //string.Concat(strMassage, "\n ", "Remark");
                bStatus = false;
            }

            if (txtConfigTypeStatusID.Text.Trim().Length == 0)
            {
                strMassage += "\n " + "configuration Status id";
                //string.Concat(strMassage, "\n ", "Remark");
                bStatus = false;
            }

            if (!bStatus)
            {
                MessageBox.Show(clsFormatter.getCommonStatusStripMessage(StatusStripMessageTypes.WhenInsert, strMassage), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
            }

            return bStatus;

        }

