        static bool IsUpdate = false;
        public string glbUserID = "";
        //to keep form detail       
        string sFormConfigCode;
           public int iFormID;
        public bool bNoAccess;
        #endregion

        #region Form Load
        public frm_securityConfigTypeValue()
        {
            sFormConfigCode = clsAutocode.getFormConfigCode(FormName.SecurityConfigTypeValue);
            iFormID = clsSecurity.getFormID(FormName.SecurityConfigTypeValue);
            if (!clsSecurity.PermissionToRead(clsSecurity.UserIDLoged, iFormID))
            {
                bNoAccess = true;
            }

            InitializeComponent();
        }

        private void frm_securityConfigTypeValue_Load(object sender, EventArgs e)
        {
            //format Form
            RefreshGrid();
            CusDataGridViewFormat();

            ClearFields();
        } 
