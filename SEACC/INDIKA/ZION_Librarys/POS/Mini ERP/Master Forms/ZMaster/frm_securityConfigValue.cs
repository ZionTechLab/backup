        #region Refresh Grid
        private void RefreshGrid()
        {
            try
            {
                int iRow;
                dgvDetail.Rows.Clear();

                List<tbl_securityConfigValue> details = tbl_securityConfigValue.SelectAll();
                foreach (tbl_securityConfigValue detail in details)
                {
                    if (detail.ValueID != 0)
                    {
                        dgvDetail.Rows.Add();
                        iRow = dgvDetail.Rows.Count - 1;
                        dgvDetail["ValueID", iRow].Value = detail.ValueID;
                        dgvDetail["ValueName", iRow].Value = detail.ValueName;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion

        #region Clear Fields
        private void ClearFields()
        {
            //set the flag and enable the id
            IsUpdate = false;
            clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtTypeValueID, true);
            clsCommon.SetEnableDisable_NormalLabel(lblTypeValueID, true);


            txtTypeValueName.Clear();
            txtValue.Clear();
            txtConfigTypeValueID.Clear();

            if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                txtTypeValueID.Text = "<Auto Generate>";
            else
                txtTypeValueID.Clear();
            if (txtTypeValueID.Enabled)
            {
                txtTypeValueID.SelectAll();
                txtTypeValueID.Focus();
            }
        }
        #endregion

        #region Fill Details

        private void FillDetails(string sID)
        {
            try
            {
                int iId;

                if (sID.Length > 0)
                {
                    int.TryParse(sID, out iId);
                    tbl_securityConfigValue detail = tbl_securityConfigValue.Select(iId);
                    if (detail != null)
                    {
                        //set the update flag and Locked
                        IsUpdate = true;
                        clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtTypeValueID, false);
                        clsCommon.SetEnableDisable_NormalLabel(lblTypeValueID, false);

                        //asign values
                        txtTypeValueID.Text =Convert.ToString( detail.ValueID);
                        txtConfigTypeValueID.Text = detail.ConfigTypeValue_ID;
                        txtTypeValueName.Text = detail.ValueName;
                        txtValue.Text = detail.ConfigValue;

                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }

