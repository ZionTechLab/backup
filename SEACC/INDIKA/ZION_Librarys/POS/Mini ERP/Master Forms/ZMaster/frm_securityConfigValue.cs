        #region Btn Save
        private void btnSave_Click(object sender, EventArgs e)
        {
            if (CheckValidity())
            {
                if (CheckNumberValidity())
                {
                    if (clsSecurity.PermissionToSave(clsSecurity.UserIDLoged, iFormID, IsUpdate))
                    {
                        try
                        {
                            Cursor = Cursors.WaitCursor;
                            int iIdValue;
                            int.TryParse(txtTypeValueID.Text.Trim(), out iIdValue);

                            if (txtTypeValueID.Text.Trim().Length > 0)
                            {
                                if (IsUpdate)  //update records
                                {
                                    tbl_securityConfigValue oldRecord = tbl_securityConfigValue.Select(iIdValue);
                                    if (oldRecord != null)
                                    {
                                        tbl_securityConfigValue detail = new tbl_securityConfigValue(iIdValue, txtTypeValueName.Text.Trim(), txtValue.Text.Trim(), txtConfigTypeValueID.Text.Trim(), oldRecord.Form_ID);
                                        detail.Update();
                                        MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.ModifyDone), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                                    }
                                }
                                else
                                {
                                    if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                                        iIdValue = clsAutocode.getAutoGeneratedCode_ForInteger(sFormConfigCode);

                                    //Inquiry Header
                                    tbl_securityConfigValue detail = new tbl_securityConfigValue(iIdValue, txtTypeValueName.Text.Trim(), txtValue.Text.Trim(), txtConfigTypeValueID.Text.Trim(),0);
                                    detail.Insert();
                                    MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.SaveDone), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                                }

                            }
                            else
                            {
                                MessageBox.Show("Value " + clsFormatter.GetMessageFrom(MessageType.IDIsEmpty), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                            }

                        }

                        catch (Exception ex)
                        {
                            clsValidate.WriteErrorLog("", iFormID,ex);
                            SEACCException.Show(ex);
                        }
                        finally
                        {
                            Cursor = Cursors.Default;
                            ClearFields();
                            RefreshGrid();
                        }
                    }
                }
            }
        } 
