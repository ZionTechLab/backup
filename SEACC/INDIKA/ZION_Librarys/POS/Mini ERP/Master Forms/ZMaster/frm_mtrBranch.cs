        #region Clear Fields
        private void ClearFields()
        {
            //set the flag and enble the id
            IsUpdate = false;
            clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtBranchID, true);
            clsCommon.SetEnableDisable_NormalLabel(lblBranchD, true);

            txtBankName.Tag = null;
            txtBankName.Clear();
            txtBranchName.Clear();
            txtOriginalBranchCode.Clear();

            if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                txtBranchID.Text = "<Auto Generate>";
            else
                txtBranchID.Clear();
            if (txtBranchID.Enabled)
            {
                txtBranchID.SelectAll();
                txtBranchID.Focus();
            }
        }
        #endregion

        #region Refresh Grid
        private void RefreshGrid()
        {
            try
            {
                int iRow;
                dgvDetail.Rows.Clear();
                List<tbl_zBankBranches> details = tbl_zBankBranches.SelectAll();
                foreach (tbl_zBankBranches detail in details)
                {
                    //MessageBox.Show("ok");
                    if (detail.Branch_ID.Trim() != "default")
                    {
                        dgvDetail.Rows.Add();
                        iRow = dgvDetail.Rows.Count - 1;
                        dgvDetail["BranchID", iRow].Value = detail.Branch_ID;
                        dgvDetail["BranchName", iRow].Value = detail.BranchName;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion

        #region Fill Details
        private void FillDetails(string sID)
        {
            try
            {
                if (sID.Length > 0)
                {
                    tbl_zBankBranches detail = tbl_zBankBranches.Select(sID);
                    if (detail != null)
                    {
                        //set the update flag and Locked
                        IsUpdate = true;
                        clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtBranchID, false);
                        clsCommon.SetEnableDisable_NormalLabel(lblBranchD, false);

                        //asign values
                        txtBankName.Tag = detail.Bank_ID;
                        txtBankName.Text = clsCommon.GetForeignKeyValue(clsGenaralName.getName_Bank(detail.Bank_ID));
                        txtBranchID.Text = detail.Branch_ID;
                        txtBranchName.Text = detail.BranchName;
                        txtOriginalBranchCode.Text = detail.OriginalBranchCode;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion


        #region Check Validity
        private bool CheckValidity()
        {
            string strMessage = "";
            bool bStatus = true;
            try
            {
                if (txtBankName.TextLength == 0)
                {
                    strMessage += "\n" + "Bank Name ";
                    bStatus = false;
                }
                if (txtBranchName.TextLength == 0)
                {
                    strMessage += "\n" + "Branch Name ";
                    bStatus = false;
                }
                if (bStatus == false)
                {
                    MessageBox.Show(clsFormatter.getCommonStatusStripMessage(StatusStripMessageTypes.WhenInsert, strMessage), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
            return bStatus;
        }

