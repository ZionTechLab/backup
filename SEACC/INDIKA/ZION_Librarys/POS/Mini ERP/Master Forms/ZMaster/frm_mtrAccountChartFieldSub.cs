        #region Refresh Grid
        private void RefreshGrid()
        {
            try
            {
                int iRow;
                dgvDetail.Rows.Clear();
                List<tbl_zMachineCategory_Sub> details = tbl_zMachineCategory_Sub.SelectAll();
                foreach (tbl_zMachineCategory_Sub detail in details)
                {
                    if (detail.MachineCategory_ID.Trim() != "default")
                    {
                        dgvDetail.Rows.Add();
                        iRow = dgvDetail.Rows.Count - 1;
                        dgvDetail["CategoryID", iRow].Value = detail.MachineCategorySub_ID;
                        dgvDetail["CategoryName", iRow].Value = detail.CategorySubName;
                        dgvDetail["Prifix", iRow].Value = detail.Prefrix;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion

        #region Fill Details
        private void FillDetails(string sID)
        {
            try
            {
                if (sID.Length > 0)
                {
                    tbl_zMachineCategory_Sub detail = tbl_zMachineCategory_Sub.Select(sID);
                    if (detail != null)
                    {
                        //set the update flag and Locked
                        IsUpdate = true;
                        clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtSubCategoryID, false);
                        clsCommon.SetEnableDisable_NormalLabel(lblBankID, false);

                        //asign values
                        txtCategoryName.Tag = detail.MachineCategory_ID;
                        txtCategoryName.Text = clsCommon.GetForeignKeyValue(clsGenaralName.getName_MachineCategory(detail.MachineCategory_ID));
                        txtSubCategoryID.Text = detail.MachineCategorySub_ID;
                        txtSubCategoryName.Text = detail.CategorySubName;
                        txtPrifix.Text = detail.Prefrix;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion


        #region Check Validity
        private bool CheckValidity()
        {
            string strMessage = "";
            bool bStatus = true;
            try
            {
                if (txtCategoryName.TextLength == 0)
                {
                    strMessage += "\n" + " Category Name ";
                    bStatus = false;
                }
                if (txtSubCategoryName.TextLength == 0)
                {
                    strMessage += "\n" + " Sub Category Name ";
                    bStatus = false;
                }
                if (txtPrifix.TextLength == 0)
                {
                    strMessage += "\n" + " Sub Prifix Name ";
                    bStatus = false;
                }
                foreach (DataGridViewRow row in dgvDetail.Rows)
                {
                    if (clsValidate.ValidateGridValue(dgvDetail, "Prifix", row.Index, "").ToString() == txtPrifix.Text.ToUpper() && IsUpdate == false && txtPrifix.TextLength != 0)
                    {
                        strMessage += "\n" + " You Can't Enter Same Prifix Name ";
                        bStatus = false;
                        break;
                    }
                }
                if (bStatus == false)
                {
                    MessageBox.Show(clsFormatter.getCommonStatusStripMessage(StatusStripMessageTypes.WhenInsert, strMessage), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }

            return bStatus;
        }

