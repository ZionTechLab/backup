        #region Btn Save
        private void btnSave_Click(object sender, EventArgs e)
        {
            if (CheckValidity())
            {
                if (CheckNumberValidity())
                {
                   if (clsSecurity.PermissionToSave(clsSecurity.UserIDLoged, iFormID, IsUpdate))
                    {
                        try
                        {
                            Cursor = Cursors.WaitCursor;
                            if (txtSubCategoryID.TextLength > 0)
                            {
                                if (IsUpdate)  //update records
                                {
                                    tbl_zMachineCategory_Sub oldRecord = tbl_zMachineCategory_Sub.Select(txtSubCategoryID.Text.Trim());
                                    if (oldRecord != null)
                                    {
                                        tbl_zMachineCategory_Sub detail = new tbl_zMachineCategory_Sub(txtSubCategoryID.Text.Trim(), txtCategoryName.Tag.ToString(), txtSubCategoryName.Text.Trim(), txtPrifix.Text.Trim().ToUpper());
                                        detail.Update();
                                        MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.ModifyDone), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                                    }
                                }
                                else  //insert records
                                {
                                    if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                                        txtSubCategoryID.Text = clsAutocode.getAutoGeneratedCode(sFormConfigCode);

                                   //Inquiry Header
                                    tbl_zMachineCategory_Sub detail = new tbl_zMachineCategory_Sub(txtSubCategoryID.Text.Trim(), txtCategoryName.Tag.ToString(), txtSubCategoryName.Text.Trim(), txtPrifix.Text.Trim().ToUpper());
                                    detail.Insert();
                                    MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.SaveDone), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                                }
                            }
                            else
                            {
                                MessageBox.Show("Item sub Category " + clsFormatter.GetMessageFrom(MessageType.IDIsEmpty), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                            }
                        }
                        catch (Exception ex)
                        {
                            clsValidate.WriteErrorLog("", iFormID,ex);
                            SEACCException.Show(ex);
                        }
                        finally
                        {
                            Cursor = Cursors.Default;
                            ClearFields();
                            RefreshGrid();
                        }
                    }
                }
            }
        }
