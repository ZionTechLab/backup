        #region Btn Save
        private void btnSave_Click(object sender, EventArgs e)
        {
            if (tabControl1.SelectedTab == currencyMaster)
            {
                if (CheckValidity())
                {
                    if (CheckNumberValidity())
                    {
                        if (clsSecurity.PermissionToSave(clsSecurity.UserIDLoged, iFormID, IsUpdate))
                        {
                            try
                            {
                                Cursor = Cursors.WaitCursor;
                                if (txtCurrencyID.TextLength > 0)
                                {
                                    if (IsUpdate)  //update records
                                    {
                                        tbl_zCurrency oldRecord = tbl_zCurrency.Select(txtCurrencyID.Text.Trim());
                                        if (oldRecord != null)
                                        {
                                            //Country Header
                                            tbl_zCurrency detail = new tbl_zCurrency(txtCurrencyID.Text.Trim(), txtCurrencyName.Text.Trim(), txtCurrencyCode.Text.Trim(), decimal.Parse(txtCurrencyRate.Text), decimal.Parse(txtBuyingRate.Text), clsSecurity.getServerDateTime());
                                            detail.Update();

                                            //insert histry record
                                            tbl_zCurrency_History detail2 = new tbl_zCurrency_History(clsHelpMethods.GetMaxzimumLineNoCurrencyMasterHistory(txtCurrencyID.Text.Trim()), txtCurrencyID.Text.Trim(), dtpCurrencyMasValiFrom.Value, clsSecurity.getServerDateTime(), decimal.Parse(txtCurrencyRate.Text), decimal.Parse(txtBuyingRate.Text), "", clsSecurity.UserIDLoged, clsSecurity.TerminalID, clsSecurity.getServerDateTime());
                                            detail2.Insert();
                                            clsHelpMethods.InsertTransactionHistory(iFormID, txtCurrencyID.Text, TxnActivity.Update);
                                            MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.ModifyDone), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                                        }
                                    }
                                    else  //insert records
                                    {
                                        if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                                            txtCurrencyID.Text = clsAutocode.getAutoGeneratedCode(sFormConfigCode);

                                        //Inquiry Header
                                        tbl_zCurrency detail = new tbl_zCurrency(txtCurrencyID.Text.Trim(), txtCurrencyName.Text.Trim(), txtCurrencyCode.Text.Trim(), decimal.Parse(txtCurrencyRate.Text), decimal.Parse(txtBuyingRate.Text), clsSecurity.getServerDateTime());
                                        detail.Insert();

                                        //insert histry record
                                        tbl_zCurrency_History detail2 = new tbl_zCurrency_History(clsHelpMethods.GetMaxzimumLineNoCurrencyMasterHistory(txtCurrencyID.Text.Trim()), txtCurrencyID.Text.Trim(), dtpCurrencyMasValiFrom.Value, clsSecurity.getServerDateTime(), decimal.Parse(txtCurrencyRate.Text), decimal.Parse(txtBuyingRate.Text), "default", clsSecurity.UserIDLoged, clsSecurity.TerminalID, clsSecurity.getServerDateTime());
                                        detail2.Insert();
                                        clsHelpMethods.InsertTransactionHistory(iFormID, txtCurrencyID.Text, TxnActivity.Insert);
                                        MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.SaveDone), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                                    }
                                }
                                else
                                {
                                    MessageBox.Show("Currency " + clsFormatter.GetMessageFrom(MessageType.IDIsEmpty), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                                }
                            }
                            catch (Exception ex)
                            {
                                clsValidate.WriteErrorLog("", iFormID,ex);
                                SEACCException.Show(ex);
                            }
                            finally
                            {
                                Cursor = Cursors.Default;
                                ClearFields();
                                RefreshGrid();
                                //RefreshGridHistory();
                            }
                        }
                    }
                }

            }
        }


