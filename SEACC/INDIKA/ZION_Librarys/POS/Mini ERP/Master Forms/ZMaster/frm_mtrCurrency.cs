        #region Fill Details
        private void FillDetails(string cID)
        {
            try
            {
                if (cID.Length > 0)
                {
                    tbl_zCurrency detail = tbl_zCurrency.Select(cID);
                    if (detail != null)
                    {
                        //set the update flag and Locked
                        IsUpdate = true;
                        clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtCurrencyID, false);
                        clsCommon.SetEnableDisable_NormalTextbox(txtCurrencyName, true);
                        clsCommon.SetEnableDisable_NormalTextbox(txtCurrencyCode, true);
                        clsCommon.SetEnableDisable_NormalTextbox(txtCurrencyRate, true);

                        //asign values
                        txtCurrencyID.Text = detail.Currency_ID;
                        txtCurrencyName.Text = detail.CurrencyName;
                        txtCurrencyCode.Text = detail.CurrencyCode;
                        txtCurrencyRate.Text = detail.CurrencyRate.ToString();
                    }

                    RefreshGridHistoryByCurrencyID(cID);
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion

        #region Datagrid Format
        private void CusDataGridViewFormat()
        {
            clsFormatter.ApplyGridFormat(dgvDetail);
            clsFormatter.ApplyGridFormat(dgvDetailHistory);
        }
        #endregion

        #region Clear Fields
        private void ClearFields()
        {
            //set the flag and enble the id
            IsUpdate = false;
            clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtCurrencyID, true);
            clsCommon.SetEnableDisable_NormalTextbox(txtCurrencyName, true);
            clsCommon.SetEnableDisable_NormalTextbox(txtCurrencyCode, true);
            clsCommon.SetEnableDisable_NormalTextbox(txtCurrencyRate, true);

            txtCurrencyName.Clear();
            txtCurrencyCode.Clear();
            txtCurrencyRate.Clear();
            txtBuyingRate.Text = "0.00";

            if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                txtCurrencyID.Text = "<Auto Generate>";
            else
                txtCurrencyID.Clear();
            if (txtCurrencyID.Enabled)
            {
                txtCurrencyID.SelectAll();
                txtCurrencyID.Focus();
            }
            dgvDetailHistory.Rows.Clear();
        }
        #endregion

        #region Refresh
        private void RefreshGrid()
        {
            try
            {
                int iRow;
                dgvDetail.Rows.Clear();
                List<tbl_zCurrency> details = tbl_zCurrency.SelectAll();
                foreach (tbl_zCurrency detail in details)
                {
                    if (detail.Currency_ID.Trim() != "default")
                    {
                        dgvDetail.Rows.Add();
                        iRow = dgvDetail.Rows.Count - 1;
                        dgvDetail["CurrencyID", iRow].Value = detail.Currency_ID;
                        dgvDetail["CurrencyName", iRow].Value = detail.CurrencyName;
                        dgvDetail["currencyCode", iRow].Value = detail.CurrencyCode;
                        dgvDetail["currencyRate", iRow].Value = detail.CurrencyRate;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }

        private void RefreshGridHistory() 
        {
            try
            {
                int iRow;
                dgvDetailHistory.Rows.Clear();
                List<tbl_zCurrency_History> details = tbl_zCurrency_History.SelectAll();
                foreach (tbl_zCurrency_History detail in details)
                {
                    if (detail.Currency_ID.Trim() != "default")
                    {
                        dgvDetailHistory.Rows.Add();
                        iRow = dgvDetailHistory.Rows.Count - 1;
                        dgvDetailHistory["ValidateFrom", iRow].Value = clsFormatter.FormatDate_Short(detail.DateValidFrom);
                        dgvDetailHistory["ValidateTill", iRow].Value = clsFormatter.FormatDate_Short(detail.DateValidTill);
                        dgvDetailHistory["CRate", iRow].Value = detail.CurrencyRate;
                        dgvDetailHistory["ModifiedUser", iRow].Value = detail.CreateUser_ID;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }

        private void RefreshGridHistoryByCurrencyID(string sID)
        {
            try
            {
                int iRow;
                dgvDetailHistory.Rows.Clear();
                List<tbl_zCurrency_History> details = tbl_zCurrency_History.SelectAllByCurrency_ID(sID);
                foreach (tbl_zCurrency_History detail in details)
                {
                    if (detail.Currency_ID.Trim() != "default")
                    {
                        dgvDetailHistory.Rows.Add();
                        iRow = dgvDetailHistory.Rows.Count - 1;
                        dgvDetailHistory["ValidateFrom", iRow].Value = clsFormatter.FormatDate_Short(detail.DateValidFrom);
                        dgvDetailHistory["ValidateTill", iRow].Value = clsFormatter.FormatDate_Short(detail.DateValidTill);
                        dgvDetailHistory["CRate", iRow].Value = detail.CurrencyRate;
                        dgvDetailHistory["ModifiedUser", iRow].Value = detail.CreateUser_ID;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }

