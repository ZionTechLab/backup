        #region Datagrid Format
        private void CusDataGridViewFormat()
        {
            clsFormatter.ApplyGridFormat(dgvDetail);
        }
        #endregion

        #region Clear Fields
        private void ClearFields()
        {
            //set the flag and enble the id
            IsUpdate = false;
            clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtCostCenterID, true);
            clsCommon.SetEnableDisable_NormalLabel(lblCostCenterID, true);

            txtCostCenterName.Clear();

            if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                txtCostCenterID.Text = "<Auto Generate>";
            else
                txtCostCenterID.Clear();
            if (txtCostCenterID.Enabled)
            {
                txtCostCenterID.SelectAll();
                txtCostCenterID.Focus();
            }
        }
        #endregion

        #region Refresh Grid
        private void RefreshGrid()
        {
            try
            {
                int iRow;
                dgvDetail.Rows.Clear();
                List<  tbl_zCost_Center4> details =   tbl_zCost_Center4.SelectAll().Where(p=> !p.IsCanceled).ToList();
                foreach (  tbl_zCost_Center4 detail in details)
                {
                    if (detail.Cost_Center4_ID != "default")
                    {

                        dgvDetail.Rows.Add();
                        iRow = dgvDetail.Rows.Count - 1;
                        dgvDetail["clmCostCenterID", iRow].Value = detail.Cost_Center4_ID;
                        dgvDetail["clmCostCenterName", iRow].Value = detail.Cost_Center4_Name;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion

        #region Fill Details
        private void FillDetails(string sID)
        {
            try
            {
                if (sID.Length > 0)
                {
                      tbl_zCost_Center4 detail =   tbl_zCost_Center4.Select(sID);
                    if (detail != null)
                    {
                        //set the update flag and Locked
                        IsUpdate = true;
                        clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtCostCenterID, false);
                        clsCommon.SetEnableDisable_NormalLabel(lblCostCenterID, false);

                        //asign values
                        txtCostCenterID.Text = detail.Cost_Center4_ID;
                        txtCostCenterName.Text = detail.Cost_Center4_Name;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
        #endregion

        #region Check Validity
        private bool CheckValidity()
        {
            string strMessage = "";
            bool bStatus = true;

            if (txtCostCenterName.TextLength == 0)
            {
                strMessage += "\n" + "Cost Center Name ";
                bStatus = false;
            }
            if (bStatus == false)
            {
                MessageBox.Show(clsFormatter.getCommonStatusStripMessage(StatusStripMessageTypes.WhenInsert, strMessage), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            return bStatus;
        }

