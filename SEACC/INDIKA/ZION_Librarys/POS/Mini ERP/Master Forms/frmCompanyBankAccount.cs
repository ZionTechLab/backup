        #region Check Validity
        private bool CheckValidity_EmptyField()
        {
            bool bStatus = false;
            if (clsValidate.ValidateTextBox_EmptyValue(txtAccountNo, "Company Bank Account"))
                if (clsValidate.ValidateTextBox_EmptyValue(txtBankID, "Bank"))
                    if (clsValidate.ValidateTextBox_EmptyValue(txtBankBranchID, "Bank Branch"))
                        if (clsValidate.ValidateTextBox_EmptyValue(txtControlAccID, "Controll Account"))
                            bStatus = true;

            return bStatus;
        }

        private bool CheckValidity_AccNoLength()
        {
            bool bStatus = true;
            if (txtAccountNo.Text.Length < 4)
            {
                bStatus = false;
                MessageBox.Show("Please check Account No. ", clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
            }

            return bStatus;
        }
        private bool CheckValidity_DuplicateAccountNo(string sAccountNo)
        {
            bool bStatus = true;

            tbl_accGLMaster_Bank oOldBank = tbl_accGLMaster_Bank.Select(sAccountNo);
            tbl_genCompanyAccount oOldCom = tbl_genCompanyAccount.Select(sAccountNo);
            //foreach (tbl_genCompanyAccount oOldCom in tbl_genCompanyAccount.SelectAll().Where(p => p.AccountNumber == sAccountNo))
            //{
            //    bStatus = false;
            //} 

            if (oOldCom != null || oOldBank != null)
                bStatus = false;

            if (bStatus == false)
                MessageBox.Show("This Account No. is already added. ", clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);

            return bStatus;
        }

        private bool CheckValidityDuplicate_ControlAccount(string sAccountNo)
        {
            bool bStatus = true;

            if (txtControlAccID.Tag.ToString() == "default")
            {
                bStatus = false;
                MessageBox.Show("Please add a Control Account .. ", clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
            }

            else
            {
                List<tbl_accGLMaster_Bank> oBanks = tbl_accGLMaster_Bank.SelectAllByGl_ID(txtControlAccID.Tag.ToString()).ToList();
                if (oBanks.Count >= 1)
                {
                    bStatus = false;
                    MessageBox.Show("This Control Account is already added. ", clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                }
            }

            return bStatus;
        }
        private bool CheckValidity_SelectBankAcc_Transaction()
        {
            bool bStatus = true;
            int iAccountNo = int.Parse(txtAccountNo.Tag.ToString());

            if (iAccountNo != null)
            {
                List<tbl_accChequeRegister> oAccCheq = tbl_accChequeRegister.SelectAll().Where(p => p.CompanyAccount_ID == iAccountNo).ToList();
                if (oAccCheq.Count > 0)
                    bStatus = false;

                List<tbl_bpsChequeRegister> oBpsCheq = tbl_bpsChequeRegister.SelectAll().Where(p => p.DepositedAccountNumber == txtAccountNo.Text.ToString()).ToList();
                if (oBpsCheq.Count > 0)
                    bStatus = false;

                if (bStatus == false)
                    MessageBox.Show("Already traded with this account. ", clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
            }

            return bStatus;
        }
