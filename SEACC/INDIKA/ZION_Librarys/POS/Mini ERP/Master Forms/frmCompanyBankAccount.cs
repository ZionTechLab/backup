        #region Fill Details
        private void FillDetails(string sAccountID)
        {
            txtControlAccID.Tag = null;
            txtControlAccID.Clear();

            if (sAccountID.Length > 0)
            {
                tbl_genCompanyAccount oCompany = tbl_genCompanyAccount.Select(sAccountID);
                if (oCompany != null)
                {
                    IsUpdate = true;
                    clsCommon.SetEnableDisable_ForeignKeyTextboxMust(txtAccountNo, false);

                    txtAccountNo.Tag = oCompany.CompanyAccount_ID;
                    txtAccountNo.Text = oCompany.AccountNumber;

                    txtBankBranchID.Tag = oCompany.Branch_ID;
                    txtBankBranchID.Text = clsGenaralName.getName_BankBranch(oCompany.Branch_ID);
                    txtBankID.Tag = oCompany.Bank_ID;
                    txtBankID.Text = clsGenaralName.getName_Bank(oCompany.Bank_ID);
                    txtPrefix.Tag = oCompany.Prefix;
                    txtPrefix.Text = oCompany.Prefix;

                    txtChequeFormat.Tag = oCompany.ChequeFormat_ID;
                    txtChequeFormat.Text = clsGenaralName.getChequeFormat_Code(oCompany.ChequeFormat_ID);

                    tbl_accGLMaster_Bank oBank = tbl_accGLMaster_Bank.Select(sAccountID);
                    if (oBank != null)
                    {
                        txtControlAccID.Tag = oBank.Gl_ID;
                        txtControlAccID.Text = clsGenaralName.getName_AccountName(oBank.Gl_ID);
                    }
                }
            }
        }
