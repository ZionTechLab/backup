        #region Events Datagrid
        private void dgvAccounts_CellClick(object sender, DataGridViewCellEventArgs e)
        {
            if (e.RowIndex >= 0)
            {
                string sColName = "";
                if (e.ColumnIndex >= 0)
                    sColName = dgvAccounts.Columns[e.ColumnIndex].Name;

                if (sColName == "AccountNo" || sColName == "BankName" || sColName == "BranchName" || sColName == "GLCode")
                {
                    string sAccountNo = clsValidate.ValidateGridValue(dgvAccounts, "AccountNo", e.RowIndex, "");
                    if (sAccountNo != null)
                    {
                        FillDetails(sAccountNo);
                    }
                }
            }
        }
