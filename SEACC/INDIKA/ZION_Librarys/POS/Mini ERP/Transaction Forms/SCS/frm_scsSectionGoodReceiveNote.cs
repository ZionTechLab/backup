        private bool CheckStockValidityWhenRemove(string sNoteID)
        {
            string strMessage = "", sItemCode = "", sJobCode = "";
            decimal dWeightActual = 0;
            decimal dQty = 0;
            bool bStatus = true;

            List<tbl_scsSectionGoodReceiveNote_Detail> details = tbl_scsSectionGoodReceiveNote_Detail.SelectAllBySectionGoodReceiveNote_ID(sNoteID);
            foreach (tbl_scsSectionGoodReceiveNote_Detail GRNdetail in details)
            {
                sItemCode = GRNdetail.Item_ID;
                dWeightActual = GRNdetail.Weight;
                dQty = GRNdetail.Qty;
                sJobCode = GRNdetail.Job_ID;
                if (!clsConfig.bSectionStockWithJobID)
                    sJobCode = "default";

                tbl_genSection_Stock stock = tbl_genSection_Stock.Select(txtLocationID.Tag.ToString(), sItemCode, sJobCode, "default", "default", "0", "0");
                if (stock != null)
                {
                    if (stock.Weight < dWeightActual)
                    {
                        strMessage += "Item: " + clsGenaralName.getName_Item(sItemCode) + " Stocks-in-hand is Not Sufficient Weight to Cancel this note \n";
                        bStatus = false;
                    }
                    if (stock.Qty < dQty)
                    {
                        strMessage += "Item: " + clsGenaralName.getName_Item(sItemCode) + " Stocks-in-hand is Not Sufficient Quantity to Cancel this note \n";
                        bStatus = false;
                    }
                }
                else
                {
                    strMessage += "Item: " + clsGenaralName.getName_Item(sItemCode) + " Is Not Available In " + clsGenaralName.getName_Section(txtLocationID.Tag.ToString()) + " Stock\n";
                    bStatus = false;
                }
            }

            if (bStatus == false)
            {
                MessageBox.Show(strMessage, clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            return bStatus;
        }
