        #region Refresh Grid
        private void RefreshGrid(string sGRNID)
        {
            int iRow;
            dgvDetail.Rows.Clear();

            List<tbl_scsSectionGoodReceiveNote_Detail> details = tbl_scsSectionGoodReceiveNote_Detail.SelectAllBySectionGoodReceiveNote_ID(sGRNID).OrderBy(p => p.Line_No).ToList();
            foreach (tbl_scsSectionGoodReceiveNote_Detail detail in details)
            {
                dgvDetail.Rows.Add();
                iRow = dgvDetail.Rows.Count - 1;
                string sFromLocation = clsHelpMethods.GetToLocationName(detail.FromSelectArea_ID, detail.FromDepartment_ID, detail.FromSection_ID, detail.FromStore_ID);
                string sFromNoteID = clsHelpMethods.GetSelectAreaNoteID(detail.FromSelectArea_ID, detail.DepartmentGoodIssueNote_ID, detail.SectionGoodIssueNote_ID, detail.StoreGoodIssueNote_ID);

                clsHelpMethods.Fill_StockDatagrid(dgvDetail, iRow, detail.Line_No, detail.Item_ID, detail.Uom_ID, detail.Job_ID, detail.FromSelectArea_ID,
