        #region Fill Details
        private void FillDetails(string sID)
        {
            try
            {
                if (sID.Length > 0)
                {
                    bool bPAdviced = false, bPaid = false;
                    tbl_bpsReceipt oReceipt = tbl_bpsReceipt.Select(sID);
                    if (oReceipt != null)
                    {
                        tbl_bpsReceipt_SubagentPayment detail = tbl_bpsReceipt_SubagentPayment.Select(sID);
                        if (detail != null)
                        {
                            //set the update flag and Locked
                            IsUpdate = true;
                            clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtReceiptID, false);
                            clsCommon.SetEnableDisable_NormalLabel(lblReceiptID, false); 

                            //fill order detials
                            txtReceiptID.Text = detail.Receipt_ID;
                            dtpPaymentDate.Value = detail.DateCreate;
                            txtSubAgentName.Text = detail.SubAgentName;
                            txtCashAmount.Text = clsFormatter.FormatToCurrecyWithThousendSep(detail.GrandTotal); 

                            bPAdviced = true;
                            bPaid = detail.IsPaid;
                        }
                        //receipt detail only
                        FillDetailsByReceiptID(oReceipt.Receipt_ID);

                        //Set Flow
                        clsHelpMethods.SetProcessFlow_PaymentSubAgent(txtFlowReceipt, txtFlowPAdviced, bPAdviced, txtFlowPaid, bPaid);
                    }

                }
            }
            catch { }

            finally { }
        }
        #endregion

        #region FillDetailsByReceiptID
        private void FillDetailsByReceiptID(string ReceiptID)
        {
            try
            {
                if (ReceiptID.Length > 0)
                {
                    tbl_bpsReceipt detail = tbl_bpsReceipt.Select(ReceiptID);
                    if (detail != null)
                    {
                        txtCustomerName.Tag = detail.Customer_ID;

                        dtpReceiptDate.Value = detail.ReceiptDate;
                        txtCustomerName.Text = clsGenaralName.getName_Customer(detail.Customer_ID);
                        txtReceiptTotal.Text = clsFormatter.FormatToCurrecyWithThousendSep(detail.TotalAmount);

                        tbl_zOrderRefNo order = tbl_zOrderRefNo.Select(detail.OrderRefNo_ID);
                        if (order != null)
                        {
                            txtJobNo.Text = clsCommon.GetForeignKeyValue(clsGenaralName.getName_OrderRefNo(detail.OrderRefNo_ID));
                            txtSalesRep.Text = clsCommon.GetForeignKeyValue(clsGenaralName.getName_Employee(order.Employee_ID));
                        }
                    }
                }
            }
            catch { }

            finally { }
        }

        #endregion


