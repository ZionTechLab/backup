        #region Clear Fields
        private void ClearFields()
        {
            //set the flag and enble the id
            IsUpdate = false;
            clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtReceiptID, true);
            clsCommon.SetEnableDisable_NormalLabel(lblReceiptID, true);

            txtCustomerName.Tag = null;

            txtReceiptID.Clear();
            dtpPaymentDate.Value = clsSecurity.getServerDateTime();
            txtSubAgentName.Clear();
            txtReceiptTotal.Clear();
            txtCashAmount.Text = "0.00";

            txtJobNo.Clear();
            txtSalesRep.Clear();
            dtpReceiptDate.Value = clsSecurity.getServerDateTime();
            txtCustomerName.Clear();

            txtFlowReceipt.ForeColor = Color.Gray;
            txtFlowPAdviced.ForeColor = Color.Gray;
            txtFlowPaid.ForeColor = Color.Gray;
        }
