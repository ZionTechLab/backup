                            Fill_Datagrid(iRow, objInvoice.InvoiceDate.ToShortDateString(), objInvoice.Invoice_ID, objInvoice.GrandTotal, " Invoice Issued - " + objInvoice.Invoice_ID, 0, dJEBalance, dJEBalance * -1);
