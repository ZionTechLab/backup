        private void LoadJournalEntries(string sCustomerID)
        {
            int iAmount = 0;
            try
            {
                foreach (tbl_accJournalEntry_Detail detailJED in tbl_accJournalEntry_Detail.SelectAllByCustomer_ID(sCustomerID).Where(p => !p.IsSeattled))
                {
                    tbl_accJournalEntry oJournalEntry = tbl_accJournalEntry.Select(detailJED.JournalEntry_ID);
                    if (oJournalEntry != null && !oJournalEntry.IsDeleted)
                    {
                        if (oJournalEntry.JournalEntryDate.Date >= dtpFromDate.Value.Date &&
                            oJournalEntry.JournalEntryDate.Date <= dtpToDate.Value.Date)

                        {
                            if (detailJED.IsCredit)
                            {
                                this.dgvCredits.Rows.Add();
                                int rowIndex = this.dgvCredits.Rows.Count - 1;
                                this.dgvCredits["TxnCr", rowIndex].Value = "ADJ";
                                this.dgvCredits["TxnIDCr", rowIndex].Value = detailJED.JournalEntry_ID;
                                this.dgvCredits["TxnIDCr", rowIndex].Tag = detailJED.Line_No;
                                //this.dgvCredits["refNoCr", rowIndex].Value = "-";
                                this.dgvCredits["DateCr", rowIndex].Value = oJournalEntry.JournalEntryDate;
                                this.dgvCredits["AmountCr", rowIndex].Value =
                                    (detailJED.Amount - detailJED.SeattleAmount);

                                iAmount += (int) detailJED.Amount;
                            }
                            else
                            {
                                this.dgvDebits.Rows.Add();
                                int rowIndex = this.dgvDebits.Rows.Count - 1;
                                this.dgvDebits["TxnDb", rowIndex].Value = "ADJ";
                                this.dgvDebits["TxnIDDb", rowIndex].Value = detailJED.JournalEntry_ID;
                                this.dgvDebits["TxnIDDb", rowIndex].Tag = detailJED.Line_No;
                                //this.dgvDebits["refNoDb", rowIndex].Value = "-";
                                this.dgvDebits["DateDb", rowIndex].Value = oJournalEntry.JournalEntryDate;
                                this.dgvDebits["AmountDb", rowIndex].Value =
                                    (detailJED.Amount - detailJED.SeattleAmount);

                                iAmount += (int) detailJED.Amount;
                            }
                        }
                    }
                }

            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID, ex);
                SEACCException.Show(ex);
            }
            this.pgrInvoice.Maximum = iAmount;
            this.pgrPayment.Maximum = iAmount;

        }
