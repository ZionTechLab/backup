        #region Calculate Invoice
        private void calculateInvoice()
        {
            decimal dInvoiceTotal = 0;
            foreach (Control con in zpnlSelettedInvoice.Controls)
            {
                int iLineNo = 0;
                string[] theSplit = con.Tag.ToString().Split('-');
                if (theSplit.Length > 1)
                    iLineNo = int.Parse(con.Tag.ToString().Split('-').Last());

                if (con is TextBox && con.Visible == true)
                {
                    tbl_sasInvoice detail = tbl_sasInvoice.Select(con.Name);
                    List<tbl_accJournalEntry_Detail> JED = tbl_accJournalEntry_Detail.SelectAllByJournalEntry_ID(con.Name).Where(p => p.Line_No == iLineNo).ToList();
                    if (detail != null)
                    {
                        try
                        {
                            dInvoiceTotal += (detail.GrandTotal - detail.SeattleAmount);
                        }
                        catch (Exception) { }
                    }

                    else if (JED.Count > 0)
                    {
                        try
                        {
                            dInvoiceTotal += (JED.FirstOrDefault().Amount - JED.FirstOrDefault().SeattleAmount);
                        }
                        catch (Exception) { }

                    }
                }
            }

            try
            {
                pgrInvoice.Value = int.Parse(dInvoiceTotal.ToString());
            }
            catch (Exception)
            {
                pgrInvoice.Value = pgrInvoice.Maximum;
            }
            lblInvoiceAmount.Text = clsFormatter.FormatToCurrecyWithThousendSep(dInvoiceTotal);
            calculateBalance();
            FillDetail();
        }
