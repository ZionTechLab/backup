        #region Load Invoice
        private void LoadInvoice(string sCustomerID)
        {
            int iAmount = 0;
            try
            {
                List<tbl_sasInvoice> details = tbl_sasInvoice.SelectAllByCustomer_ID(sCustomerID);
                if (cbxActiveFilter.Checked)
                    details = details.Where(p => p.InvoiceDate >= dtpFromDate.Value.Date && p.InvoiceDate <= dtpToDate.Value.Date).ToList();
                foreach (tbl_sasInvoice detail in details.Where(p => p.Invoice_ID != "default" && !p.IsDeleted && !p.IsSeattled && (p.GrandTotal- p.SeattleAmount)!=0))
                {
                    //FillInvoice(detail);
                    this.dgvDebits.Rows.Add();
                    int rowIndex = this.dgvDebits.Rows.Count - 1;
                    this.dgvDebits["TxnDb", rowIndex].Value = "INV";
                    this.dgvDebits["TxnIDDb", rowIndex].Value = detail.Invoice_ID;
                    //this.dgvDebits["refNoDb", rowIndex].Value = "-";
                    this.dgvDebits["DateDb", rowIndex].Value = detail.InvoiceDate;
                    this.dgvDebits["AmountDb", rowIndex].Value = (detail.GrandTotal - detail.SeattleAmount);

                    iAmount += (int)detail.GrandTotal;
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID, ex);
                SEACCException.Show(ex);
            }
            this.pgrInvoice.Maximum = iAmount;
            this.pgrPayment.Maximum = iAmount;
        }
        #endregion

        #region Load Cheques
        private void LoadCheques(string sCustomerID)
        {
            int iAmount = 0;
            try
            {
                List<tbl_bpsChequeRegister> details = tbl_bpsChequeRegister.SelectAllByCustomer_ID(sCustomerID);
                if (cbxActiveFilter.Checked)
                    details = details.Where(p => p.DateCheque >= dtpFromDate.Value.Date && p.DateCheque <= dtpToDate.Value.Date).ToList();

                foreach (tbl_bpsChequeRegister detail in details.Where(p => p.PosTransaction_ID == "-1" &&  p.ChequeRegister_ID != "default" && !p.IsDeleted && !p.IsSetteled))
                {
                    if (detail.PaymentMethod_ID == (int)PaymentMethod.Cheque)
                    {
                        //FillCheque(detail);
                        this.dgvCredits.Rows.Add();
                        int rowIndex = this.dgvCredits.Rows.Count - 1;
                        this.dgvCredits["TxnCr", rowIndex].Value = "CHQ";
                        this.dgvCredits["TxnIDCr", rowIndex].Value = detail.Receipt_ID;
                        this.dgvCredits["TxnIDCr", rowIndex].Tag = detail.ChequeRegister_ID;
                        //this.dgvCredits["refNoCr", rowIndex].Value = detail.ChequeRegister_ID;
                        this.dgvCredits["DateCr", rowIndex].Value = detail.DateCheque;
                        this.dgvCredits["AmountCr", rowIndex].Value = (detail.Amount - detail.SetteledAmount);

                        iAmount += (int)detail.Amount;
                    }
                    else
                    {
                        //FillCash(detail);
                        this.dgvCredits.Rows.Add();
                        int rowIndex = this.dgvCredits.Rows.Count - 1;
                        this.dgvCredits["TxnCr", rowIndex].Value = "CSH";
                        this.dgvCredits["TxnIDCr", rowIndex].Value = detail.Receipt_ID;
                        this.dgvCredits["TxnIDCr", rowIndex].Tag = detail.ChequeRegister_ID;
                        //this.dgvCredits["refNoCr", rowIndex].Value = detail.ChequeRegister_ID;
                        this.dgvCredits["DateCr", rowIndex].Value = detail.DateCheque;
                        this.dgvCredits["AmountCr", rowIndex].Value = (detail.Amount - detail.SetteledAmount);

                        iAmount += (int)detail.Amount;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID, ex);
                SEACCException.Show(ex);
            }
            this.pgrInvoice.Maximum = iAmount;
            this.pgrPayment.Maximum = iAmount;
        }
