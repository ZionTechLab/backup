        #region Load Credit Note
        private void LoadCreditNote(string sCustomerID)
        {
            int iAmount = 0;
            try
            {
                List<tbl_bpsCreditNote> creditNs = tbl_bpsCreditNote.SelectAllByCustomer_ID(sCustomerID);
                if (cbxActiveFilter.Checked)
                    creditNs = creditNs.Where(p => p.CreditNoteDate >= dtpFromDate.Value.Date && p.CreditNoteDate <= dtpToDate.Value.Date).ToList();

