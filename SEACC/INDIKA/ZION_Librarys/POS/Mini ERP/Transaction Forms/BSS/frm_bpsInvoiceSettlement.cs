        #region Calculate Payment
        private void calculatePayment()
        {

            decimal dChequeTotal = 0;
            foreach (Control con in zpnlSettledPayment.Controls)
            {
                if (con is TextBox && con.Visible == true)
                {
                    int iLineNo = 0;
                    string[] theSplit = con.Tag.ToString().Split('-');
                    if (theSplit.Length > 1)
                        iLineNo = int.Parse(con.Tag.ToString().Split('-').Last());

                    tbl_bpsChequeRegister detail = tbl_bpsChequeRegister.Select(con.Name);
                    tbl_bpsReceipt receipt = tbl_bpsReceipt.Select(con.Name);
                    tbl_bpsCreditNote creditNote = tbl_bpsCreditNote.Select(con.Name);
                    List<tbl_accJournalEntry_Detail> JED = tbl_accJournalEntry_Detail.SelectAllByJournalEntry_ID(con.Name).Where(p => p.Line_No == iLineNo).ToList();
                    if (detail != null)
                    {
                        try
                        {
                            dChequeTotal += (detail.Amount - detail.SetteledAmount);
                        }
                        catch (Exception) { }
                    }
                    else if (receipt != null)
                    {
                        try
                        {
                            dChequeTotal += (receipt.CashAmount - receipt.SeattleAmount);
                        }
                        catch (Exception) { }
                    }
                    else if (creditNote != null)
                    {
                        try
                        {
                            dChequeTotal += (creditNote.TotalAmount - creditNote.SeattleAmount);
                        }
                        catch (Exception) { }
                    }
                    else if (JED.Count > 0)
                    {
                        try
                        {
                            dChequeTotal += (JED.FirstOrDefault().Amount - JED.FirstOrDefault().SeattleAmount);
                        }
                        catch (Exception) { }
                    }
                }
            }
            try
            {
                pgrPayment.Value = int.Parse(dChequeTotal.ToString());
            }
            catch (Exception)
            {
                pgrPayment.Value = pgrPayment.Maximum;
            }
            lblPaymentAmount.Text = clsFormatter.FormatToCurrecyWithThousendSep(dChequeTotal);
            calculateBalance();
            FillDetail();
        }
