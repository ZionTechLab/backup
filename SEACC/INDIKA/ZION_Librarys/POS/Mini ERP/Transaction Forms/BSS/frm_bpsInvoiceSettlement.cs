                                {
                                    if (dJEBalance <= dJournalEntryAvailableAmount) //if Receipt has enough cash to settled 
                                    {
                                        dSettledAmount = dJEBalance;
                                        jeRow["JournalEntryBalance"] = 0;
                                        creRow["CreditNoteBalance"] = (dJournalEntryAvailableAmount - dJEBalance);
                                    }
                                    else //if JE amount is greter than Receipt amount  
                                    {
                                        dSettledAmount = dJournalEntryAvailableAmount;
                                        jeRow["JournalEntryBalance"] = (dJEBalance - dJournalEntryAvailableAmount);
                                        creRow["CreditNoteBalance"] = 0;
                                    }
                                    //add to grid
                                    dgvDetail.Rows.Add();
                                    iRow = dgvDetail.Rows.Count - 1;
                                    Fill_Datagrid(iRow, "", "", objCreditNote.SeattleAmount, " Credit Note Issued - " + objCreditNote.CreditNote_ID, dSettledAmount, 0, getJEBalance(jeRow));
                                }
                            }
                        }
                        #endregion

                        #region settle with Journal Entry
                        foreach (DataRow jeCrRow in dtJournalEntry_Cr.Rows)
                        {
                            List<tbl_accJournalEntry_Detail> oJEDetail = tbl_accJournalEntry_Detail.SelectAllByJournalEntry_ID(jeCrRow["JournalEntryID"].ToString()).Where(p => p.Customer_ID == txtCustomerID.Tag.ToString() && p.Line_No == int.Parse(jeRow["lineNo"].ToString()) && p.IsCredit).ToList();

                            tbl_accJournalEntry_Detail objJournalEntry = oJEDetail.FirstOrDefault();
                            if (objJournalEntry != null)
                            {
                                dSettledAmount = 0;
                                dJournalEntryAvailableAmount = decimal.Parse(jeRow["JournalEntryBalance"].ToString());
                                dJEBalance = decimal.Parse(jeCrRow["JournalEntryBalance"].ToString());
                                if (dJournalEntryAvailableAmount > 0 && dJEBalance > 0)
                                {
                                    if (dJEBalance <= dJournalEntryAvailableAmount) //if Receipt has enough cash to settled 
                                    {
                                        dSettledAmount = dJEBalance;
                                        jeRow["JournalEntryBalance"] = 0;
                                        jeCrRow["JournalEntryBalance"] = (dJournalEntryAvailableAmount - dJEBalance);
                                    }
                                    else //if JE amount is greter than Receipt amount  
                                    {
                                        dSettledAmount = dJournalEntryAvailableAmount;
                                        jeRow["JournalEntryBalance"] = (dJEBalance - dJournalEntryAvailableAmount);
                                        jeCrRow["JournalEntryBalance"] = 0;
                                    }
                                    //add to grid
                                    dgvDetail.Rows.Add();
                                    iRow = dgvDetail.Rows.Count - 1;
                                    Fill_Datagrid(iRow, "", "", objJournalEntry.Amount, " Journal Entry Issued - " + objJournalEntry.JournalEntry_ID, dSettledAmount, 0, getJEBalance(jeRow));
                                }
                            }
