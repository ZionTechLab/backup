                        foreach (DataRow chkRow in dtCheque.Rows)
                        {
                            tbl_bpsChequeRegister objCheque = tbl_bpsChequeRegister.Select(chkRow["ChequeRegisterID"].ToString());
                            if (objCheque != null)
                            {
                                dSettledAmount = 0;
                                dChequeAvailableAmount = decimal.Parse(chkRow["ChequeBalance"].ToString());
                                dJEBalance = decimal.Parse(invRow["InvoiceBalance"].ToString());
                                if (dChequeAvailableAmount > 0 && dJEBalance > 0)
                                {
                                    if (dJEBalance <= dChequeAvailableAmount) //if Cheque has enough cash to settled 
                                    {
                                        dSettledAmount = dJEBalance;
                                        invRow["InvoiceBalance"] = 0;
                                        chkRow["ChequeBalance"] = (dChequeAvailableAmount - dJEBalance);
                                    }
                                    else //if Invoice amount is greter than Cheque amount  
                                    {
                                        dSettledAmount = dChequeAvailableAmount;
                                        invRow["InvoiceBalance"] = (dJEBalance - dChequeAvailableAmount);
                                        chkRow["ChequeBalance"] = 0;
                                    }
                                    //add to grid
                                    dgvDetail.Rows.Add();
                                    iRow = dgvDetail.Rows.Count - 1;
                                    Fill_Datagrid(iRow, "", "", objCheque.Amount, " Cheque Received - " + objCheque.ChequeNumber, dSettledAmount, 0, getInvoiceBalance(invRow));
                                }
                            }
                        }
