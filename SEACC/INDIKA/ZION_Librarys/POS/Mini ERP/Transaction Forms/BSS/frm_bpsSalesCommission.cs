                if (txtCommissionID.Tag != null)
                {
                    tbl_sasSalesCommission oSasCommission = tbl_sasSalesCommission.Select(txtCommissionID.Tag.ToString());
                    if (oSasCommission.Commission_ID != null)
                    {
                        string sCustomerName = "";
                        Int64 iDeduction_ID = 0;
                        foreach (tbl_sasSalesCommission_Deduction oDeduction in tbl_sasSalesCommission_Deduction.SelectAllByCommission_ID(oSasCommission.Commission_ID))
                        {
                            if (!oDeduction.IsInvoiceDeduction)
