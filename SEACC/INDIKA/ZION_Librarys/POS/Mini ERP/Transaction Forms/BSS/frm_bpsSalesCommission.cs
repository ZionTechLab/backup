        #region Refresh Grid Commission
        private void RefreshGrid_Commission()
        {
            try
            {
                int iRow;
                dgvInvoiceDetails.Rows.Clear();

                if (txtCommissionID.Tag != null)
                {
                    tbl_sasSalesCommission oSasCommission = tbl_sasSalesCommission.Select(txtCommissionID.Tag.ToString());
                    if (oSasCommission.Commission_ID != null)
                    {
                        foreach (tbl_sasSalesCommission_Slab oCommission in tbl_sasSalesCommission_Slab.SelectAllByCommission_ID(oSasCommission.Commission_ID))
                        {
                            if (oCommission.Commission_ID.Trim() != "default")
                            {
                                dgvInvoiceDetails.Rows.Add();
                                iRow = dgvInvoiceDetails.Rows.Count - 1;
                                Fill_Datagrid_Commission(iRow, oCommission.FromAmount, oCommission.ToAmount, oCommission.CommissionPercentage, oCommission.CommissionAmount);
                            }
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
