        #region Calculate Commission
        private void CalculateCommission()
        {
            try
            {
                Cursor = Cursors.WaitCursor;
                if (CheckValidity_EmptyField())
                {                    
                    DateTime dtFromDate = DateTime.Parse("1." + txtMonth.Text.Trim() + " " + txtYear.Text.Trim());
                    DateTime dtToDate = clsSecurity.LastDayOfMonthFromDateTime(dtFromDate);

                    List<tbl_genCustomerMaster> oCustomers = tbl_genCustomerMaster.SelectAll().Where(p => p.Customer_ID != "default" && !p.IsDeleted && p.SalesRep_ID == txtSalesPerson.Tag.ToString()).ToList();
                    foreach (tbl_genCustomerMaster oCustomer in oCustomers)
                    {                        
                        tbl_genCustomerFinance oCusFin = tbl_genCustomerFinance.Select(oCustomer.Customer_ID);
                        if (oCusFin != null && oCusFin.Customer_ID != "default")
                        {
                            #region Invoices
                            decimal dValidAmount = 0, dOverDueAmount = 0, dDeductionAmount = 0;
                            foreach (tbl_sasInvoice detail in tbl_sasInvoice.SelectAll_ByCustomerIDandDateRange(dtFromDate, dtToDate, oCustomer.Customer_ID).Where(p => p.Invoice_ID != "default" && !p.IsDeleted && !p.IsReturnedCheque && !p.IsDebitNote))
                            {
                                DateTime dtLastDayForThePayment = detail.InvoiceDate.AddDays(double.Parse(oCusFin.CommissionCreditPeriod.ToString()));
                                DateTime dtLastDayOfThePayment_ValidInvoices = detail.InvoiceDate;
                                DateTime dtLastDayOfThePayment_OverDues = detail.InvoiceDate;
                                dValidAmount = 0;
                                dOverDueAmount = 0;
                                dDeductionAmount = 0;

                                if (detail.Quotation_ID != "default" || (detail.Job_ID == "default" && detail.DeliveryOrder_ID != "default"))
                                    continue;

                                #region Payment Validation
                                foreach (tbl_sasInvoice_Sattled oSettment in tbl_sasInvoice_Sattled.SelectAllByInvoice_ID(detail.Invoice_ID))
                                {
                                    #region Cheque
                                    if (oSettment.ChequeRegister_ID != "default" && oSettment.Receipt_ID != "default") //Cheque
                                    {
                                        tbl_bpsChequeRegister oCheque = tbl_bpsChequeRegister.Select(oSettment.ChequeRegister_ID);
                                        if (oCheque != null && oCheque.ChequeRegister_ID != "default")
                                        {
                                            if (oCheque.IsReconcilied || oCheque.IsReIssued)
                                            {
                                                if (oCheque.ChequeStatus_ID != clsAutocode.getChequeStatusID(ChequeStatus.Returned_NR_C) && oCheque.ChequeStatus_ID != clsAutocode.getChequeStatusID(ChequeStatus.Returned_NR_O) && oCheque.ChequeStatus_ID != clsAutocode.getChequeStatusID(ChequeStatus.Returned_R))
                                                {
                                                    if (oCheque.DateReconcilied <= dtLastDayForThePayment)
                                                    {
                                                        //ok       
                                                        dValidAmount += oSettment.SattledAmount;
                                                        dtLastDayOfThePayment_ValidInvoices = oCheque.DateReconcilied > dtLastDayOfThePayment_ValidInvoices ? oCheque.DateReconcilied : dtLastDayOfThePayment_ValidInvoices;

                                                        dgvPaymentDetails.Rows.Add();
                                                        int iRow_Payment = dgvPaymentDetails.Rows.Count - 1;
                                                        int iDays_Payment = clsCommon.getDays(detail.InvoiceDate, oCheque.DateReconcilied);
                                                        Fill_Datagrid_Payment(iRow_Payment, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, oSettment.SattledAmount, "Cheque " + oCheque.ChequeNumber, oCheque.DateReconcilied, iDays_Payment);
                                                    }
                                                    else
                                                    {
                                                        dOverDueAmount += oSettment.SattledAmount;
                                                        dtLastDayOfThePayment_OverDues = oCheque.DateReconcilied > dtLastDayOfThePayment_OverDues ? oCheque.DateReconcilied : dtLastDayOfThePayment_OverDues;

                                                        dgvPaymentDetails.Rows.Add();
                                                        int iRow_Payment = dgvPaymentDetails.Rows.Count - 1;
                                                        int iDays_Payment = clsCommon.getDays(detail.InvoiceDate, oCheque.DateReconcilied);
                                                        Fill_Datagrid_Payment(iRow_Payment, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, oSettment.SattledAmount, "Cheque " + oCheque.ChequeNumber, oCheque.DateReconcilied, iDays_Payment);
                                                    }
                                                }
                                            }
                                            else
                                            {
                                                dOverDueAmount += oSettment.SattledAmount;
                                                dtLastDayOfThePayment_OverDues = oCheque.DateReconcilied > dtLastDayOfThePayment_OverDues ? oCheque.DateReconcilied : dtLastDayOfThePayment_OverDues;

                                                dgvPaymentDetails.Rows.Add();
                                                int iRow_Payment = dgvPaymentDetails.Rows.Count - 1;
                                                int iDays_Payment = clsCommon.getDaysUptoDate(detail.InvoiceDate);
                                                Fill_Datagrid_Payment(iRow_Payment, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, oSettment.SattledAmount, "Cheque " + oCheque.ChequeNumber, oCheque.DateReconcilied, iDays_Payment);
                                            }
                                        }
                                    }
                                    #endregion

                                    #region Cash
                                    else if (oSettment.ChequeRegister_ID == "default" && oSettment.Receipt_ID != "default")
                                    {
                                        tbl_bpsReceipt oReceipt = tbl_bpsReceipt.Select(oSettment.Receipt_ID);
                                        if (oReceipt != null && oReceipt.Receipt_ID != "default")
                                        {
                                            if (oReceipt.ReceiptDate <= dtLastDayForThePayment)
                                            {
                                                dValidAmount += oSettment.SattledAmount;
                                                dtLastDayOfThePayment_ValidInvoices = oReceipt.ReceiptDate > dtLastDayOfThePayment_ValidInvoices ? oReceipt.ReceiptDate : dtLastDayOfThePayment_ValidInvoices;

                                                dgvPaymentDetails.Rows.Add();
                                                int iRow_Payment = dgvPaymentDetails.Rows.Count - 1;
                                                int iDays_Payment = clsCommon.getDays(detail.InvoiceDate, oReceipt.ReceiptDate);
                                                Fill_Datagrid_Payment(iRow_Payment, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, oSettment.SattledAmount, "Cash " + oReceipt.Receipt_ID, oReceipt.ReceiptDate, iDays_Payment);
                                            }
                                            else
                                            {
                                                dOverDueAmount += oSettment.SattledAmount;
                                                dtLastDayOfThePayment_OverDues = oReceipt.ReceiptDate > dtLastDayOfThePayment_OverDues ? oReceipt.ReceiptDate : dtLastDayOfThePayment_OverDues;

                                                dgvPaymentDetails.Rows.Add();
                                                int iRow_Payment = dgvPaymentDetails.Rows.Count - 1;
                                                int iDays_Payment = clsCommon.getDays(detail.InvoiceDate, oReceipt.ReceiptDate);
                                                Fill_Datagrid_Payment(iRow_Payment, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, oSettment.SattledAmount, "Cash " + oReceipt.Receipt_ID, oReceipt.ReceiptDate, iDays_Payment);
                                            }
                                        }
                                    }
                                    #endregion

                                    #region Credit Note - Adding To Credit Note Total
                                    else if (oSettment.CreditNote_ID != "default")
                                    {
                                        tbl_bpsCreditNote oCreditNote = tbl_bpsCreditNote.Select(oSettment.CreditNote_ID);
                                        if (oCreditNote != null && oCreditNote.CreditNote_ID != "default")
                                        {
                                            if (oCreditNote.CreditNoteDate <= dtLastDayForThePayment)
                                            {
                                                dValidAmount += oSettment.SattledAmount;
                                                dtLastDayOfThePayment_ValidInvoices = oCreditNote.CreditNoteDate > dtLastDayOfThePayment_ValidInvoices ? oCreditNote.CreditNoteDate : dtLastDayOfThePayment_ValidInvoices;

                                                dgvPaymentDetails.Rows.Add();
                                                int iRow_Payment = dgvPaymentDetails.Rows.Count - 1;
                                                int iDays_Payment = clsCommon.getDays(detail.InvoiceDate, oCreditNote.CreditNoteDate);
                                                Fill_Datagrid_Payment(iRow_Payment, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, oSettment.SattledAmount, "CRN " + oCreditNote.CreditNote_ID, oCreditNote.CreditNoteDate, iDays_Payment);
                                            }
                                            else
                                            {
                                                dOverDueAmount += oSettment.SattledAmount;
                                                dtLastDayOfThePayment_OverDues = oCreditNote.CreditNoteDate > dtLastDayOfThePayment_OverDues ? oCreditNote.CreditNoteDate : dtLastDayOfThePayment_OverDues;

                                                dgvPaymentDetails.Rows.Add();
                                                int iRow_Payment = dgvPaymentDetails.Rows.Count - 1;
                                                int iDays_Payment = clsCommon.getDays(detail.InvoiceDate, oCreditNote.CreditNoteDate);
                                                Fill_Datagrid_Payment(iRow_Payment, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, oSettment.SattledAmount, "CRN " + oCreditNote.CreditNote_ID, oCreditNote.CreditNoteDate, iDays_Payment);
                                            }
                                        }
                                    }
                                    #endregion
                                }
                                #endregion
                
                                #region Reduce Taxes
                                dDeductionAmount = (detail.GrandTotal - detail.SeattleAmount);
                                if (oCustomer.CustomerType_ID == "2")
                                {
                                    dValidAmount = clsProcessMethods.Reduce_VATnNBT_FromGrandTotal(dValidAmount, detail.VatPercentage, detail.NbtPercentage);
                                    dDeductionAmount = clsProcessMethods.Reduce_VATnNBT_FromGrandTotal(dDeductionAmount, detail.VatPercentage, detail.NbtPercentage);
                                    dOverDueAmount = clsProcessMethods.Reduce_VATnNBT_FromGrandTotal(dOverDueAmount, detail.VatPercentage, detail.NbtPercentage);
                                } 
                                #endregion

                                #region Add Valid Invoice Detail
                                if (dValidAmount > 0)
                                {
                                    int iDaysForLastPayment = clsCommon.getDays(detail.InvoiceDate, dtLastDayOfThePayment_ValidInvoices);
                                    dgvInvoiceDetails.Rows.Add();
                                    int iRow = dgvInvoiceDetails.Rows.Count - 1;
                                    Fill_Datagrid_Invoice(iRow, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, detail.GrandTotal, dValidAmount, iDaysForLastPayment, false, "Valied");
                                }
                                #endregion

                                #region Add Deduction detail
                                if (dDeductionAmount > 0)
                                {
                                    int iDaysUntilToday = clsCommon.getDaysUptoDate(detail.InvoiceDate);                                    
                                    dgvDeductions.Rows.Add();
                                    int iRowDeduction = dgvDeductions.Rows.Count - 1;
                                    Fill_Datagrid_Deduction(iRowDeduction, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, detail.GrandTotal, iDaysUntilToday, dDeductionAmount, dDeductionAmount, 0);

                                    //Add Invoice Record                                   
                                    dgvInvoiceDetails.Rows.Add();
                                    int iRow = dgvInvoiceDetails.Rows.Count - 1;
                                    Fill_Datagrid_Invoice(iRow, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, detail.GrandTotal, dDeductionAmount, iDaysUntilToday, false, "Deduction");
                                }
                                #endregion

                                #region Add Overdue detail
                                if (dOverDueAmount > 0)
                                {
                                    int iDaysForOverDues = clsCommon.getDays(detail.InvoiceDate, dtLastDayOfThePayment_OverDues);                                    
                                    dgvOverDue.Rows.Add();
                                    int iRowOverDue = dgvOverDue.Rows.Count - 1;
                                    Fill_Datagrid_OverDues(iRowOverDue, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, detail.GrandTotal, dOverDueAmount, iDaysForOverDues);

                                    //Add Invoice Record                                    
                                    dgvInvoiceDetails.Rows.Add();
                                    int iRow = dgvInvoiceDetails.Rows.Count - 1;
                                    Fill_Datagrid_Invoice(iRow, oCustomer.CustomerName, detail.Invoice_ID, detail.InvoiceDate, detail.GrandTotal, dOverDueAmount, iDaysForOverDues, false, "OverDue");
                                }
                                #endregion
                            } 
                            #endregion

                            #region CreditNotes
                            foreach (tbl_bpsCreditNote oCRN in tbl_bpsCreditNote.SelectAll_ByCustomerIDandDateRange(dtFromDate, dtToDate, oCustomer.Customer_ID).Where(p => p.CreditNote_ID != "default" && !p.IsDeleted && p.IsSeattled))
                            {
                                decimal dCreditAmount = 0;
                                if (oCustomer.CustomerType_ID == "2")
                                {
                                    dCreditAmount = clsProcessMethods.Reduce_VATnNBT_FromGrandTotal(oCRN.TotalAmount, oCRN.VatPercentage, oCRN.NbtPercentage);                                   
                                }

                                dgvCreditNoteDetail.Rows.Add();
                                int iRow = dgvCreditNoteDetail.Rows.Count - 1;
                                Fill_Datagrid_CreditNote(iRow, oCustomer.CustomerName, oCRN.CreditNote_ID, oCRN.CreditNoteDate, dCreditAmount, clsGenaralName.getName_CreditNoteType(oCRN.CreditNoteType_ID));
                            }
                            #endregion
                        }
                    }

                    #region Add Deduction detail
                    foreach (tbl_zDeductionMaster oDeduction in tbl_zDeductionMaster.SelectAllByEmployee_ID(txtSalesPerson.Tag.ToString()).Where(p=> !p.IsSettled))
                    {
                        int iDaysForLastPayment = clsCommon.getDaysUptoDate(oDeduction.DeductionDate);
                        decimal dPendingAmount = (oDeduction.DeductionAmount - oDeduction.SettledAmount);
                        dgvDeductions.Rows.Add();
                        int iRow = dgvDeductions.Rows.Count - 1;
                        Fill_Datagrid_Deduction(iRow, oDeduction.Remark, oDeduction.Deduction_ID.ToString(), oDeduction.DeductionDate, oDeduction.DeductionAmount, iDaysForLastPayment, dPendingAmount, dPendingAmount, oDeduction.Deduction_ID);
                    }

                    #endregion

                    CalculateTotals();
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
            finally {
                Cursor = Cursors.Default;
            }
        } 
        #endregion

        #region Calculate Totals
        private void CalculateTotals()
        {
            if (CheckValidity_EmptyField())
            {
                decimal dSalesTarget = 0, dTotalValiedAmount = 0, dCreditnoteTotal = 0, dTotalCommission = 0, dDeductionTotal = 0, dExceededTotal = 0, dReimbursmentTotal = 0, dTotalPaid = 0;
                decimal dInvValied = 0, dInvOverDue = 0, dInvDeduction = 0, dInvTotal = 0, dInvRejected = 0;
                foreach (DataGridViewRow row in dgvInvoiceDetails.Rows)
                {
                    string sStatus = clsValidate.ValidateGridValue(dgvInvoiceDetails, "Status", row.Index, "");
                    decimal dAllocatedAmount = clsValidate.ValidateGridValue(dgvInvoiceDetails, "AllocationAmount", row.Index, decimal.Parse("0.00"));
                    bool bRejected = clsValidate.ValidateGridValue(dgvInvoiceDetails, "InvoiceReject", row.Index, false);

                    if (!bRejected)
                    {
                        if (sStatus == "Valied")
                            dInvValied += dAllocatedAmount;
                        else if (sStatus == "Deduction")
                            dInvDeduction += dAllocatedAmount;
                        else if (sStatus == "OverDue")
                            dInvOverDue += dAllocatedAmount;
                    }
                    else
                        dInvRejected += dAllocatedAmount;
                    dInvTotal += dAllocatedAmount;
                }
                foreach (DataGridViewRow row in dgvCreditNoteDetail.Rows)
                {
                    dCreditnoteTotal += clsValidate.ValidateGridValue(dgvCreditNoteDetail, "CR_Amount", row.Index, decimal.Parse("0.00"));
                }
                foreach (DataGridViewRow row in dgvDeductions.Rows)
                {
                    dDeductionTotal += clsValidate.ValidateGridValue(dgvDeductions, "D_DeductionAmount", row.Index, decimal.Parse("0.00"));
                }
                dTotalValiedAmount = (dInvValied - dCreditnoteTotal);

                #region Fill Grid
                dgvCommission.Rows.Clear();
                foreach (tbl_zEmployeeSlabSettings oSlab in tbl_zEmployeeSlabSettings.SelectAllByEmployee_ID(txtSalesPerson.Tag.ToString()).OrderBy(p => p.SlabID))
                {
                    decimal dAllocatedAmount = 0, dTmpTotalValiedAmount = dTotalValiedAmount;
                    decimal dAmount = 0;
                    if (dTmpTotalValiedAmount >= oSlab.ToAmount)
                    {
                        dAllocatedAmount = oSlab.ToAmount;
                        dAmount = (dAllocatedAmount * oSlab.CommissionPercentage) / 100;
                        dTotalCommission += dAmount;
                        dTmpTotalValiedAmount -= dAllocatedAmount;
                    }
                    else if (dTmpTotalValiedAmount < oSlab.ToAmount)
                    {
                        dAllocatedAmount = dTmpTotalValiedAmount;
                        dAmount = (dAllocatedAmount * oSlab.CommissionPercentage) / 100;
                        dTotalCommission += dAmount;
                        dTmpTotalValiedAmount -= dAllocatedAmount;
                    }

                    dgvCommission.Rows.Add();
                    int iRow = dgvCommission.Rows.Count - 1;
                    dgvCommission["CM_SlabID", iRow].Value = oSlab.SlabID;
                    dgvCommission["CM_FromAmount", iRow].Value = clsFormatter.FormatDecimalPlaces_Price(oSlab.FromAmount);
                    dgvCommission["CM_ToAmount", iRow].Value = clsFormatter.FormatDecimalPlaces_Price(oSlab.ToAmount);
                    dgvCommission["CM_Percentage", iRow].Value = clsFormatter.FormatToNumberWithOneDecimalPlaces(oSlab.CommissionPercentage);
                    dgvCommission["CM_Amount", iRow].Value = clsFormatter.FormatDecimalPlaces_Price(dAmount);
                }
                #endregion

                txtInvoices_Valied.Text = clsFormatter.FormatDecimalPlaces_Price(dInvValied);
                txtInvoices_OverDue.Text = clsFormatter.FormatDecimalPlaces_Price(dInvOverDue);
                txtInvoices_Deduction.Text = clsFormatter.FormatDecimalPlaces_Price(dInvDeduction);
                txtInvoices_Rejected.Text = clsFormatter.FormatDecimalPlaces_Price(dInvRejected);
                txtInvoices_Total.Text = clsFormatter.FormatDecimalPlaces_Price(dInvTotal);

                txtCom_SalesTarget.Text = clsFormatter.FormatDecimalPlaces_Price(dSalesTarget);
                txtCom_ValidInvoicesAmt.Text = clsFormatter.FormatDecimalPlaces_Price(dInvValied);
                txtCom_CreditNoteAmt.Text = clsFormatter.FormatDecimalPlaces_Price(dCreditnoteTotal);
                txtCom_ValidAmt.Text = clsFormatter.FormatDecimalPlaces_Price(dTotalValiedAmount);
                txtCom_Commission.Text = clsFormatter.FormatDecimalPlaces_Price(dTotalCommission);

                dTotalPaid = (dTotalCommission - dDeductionTotal) + dReimbursmentTotal;
                txtTot_ValidCommission.Text = clsFormatter.FormatDecimalPlaces_Price(dTotalCommission);
                txtTot_Deductions.Text = clsFormatter.FormatDecimalPlaces_Price(dDeductionTotal);
                txtTot_Reimbursed.Text = clsFormatter.FormatDecimalPlaces_Price(dReimbursmentTotal);
                txtTot_ExceededSales.Text = clsFormatter.FormatDecimalPlaces_Price(dExceededTotal);
                txtTot_Commission.Text = clsFormatter.FormatDecimalPlaces_Price(dTotalPaid);
            }
        }
        #endregion
    }

