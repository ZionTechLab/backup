        #region Search Event
        private void txtDepartmentID_MouseDoubleClick(object sender, MouseButtonEventArgs e)
        {
            var location = this.PointToScreen(new Point(0, 0));
            base.OnMouseDown(e);
            Point p = e.GetPosition(this);


            frmSearch RowDataSearch = new frmSearch();
            RowDataSearch.Left = location.X - 5;
            RowDataSearch.Top = location.Y + this.Height;
            List<string> lstResult = RowDataSearch.Show(Search.Departments);

            if (RowDataSearch.DialogResult == true)
            {
                ClearFillds();
                txtDepartmentID.Text = lstResult[0];
                txtDeptName.Text = lstResult[1];
                fillDetails(lstResult[0]);
            }
        }
        private void txtContactPerson_MouseDoubleClick(object sender, MouseButtonEventArgs e)
        {
            e.Handled = false;
            frmSearch RowDataSearch = new frmSearch();
