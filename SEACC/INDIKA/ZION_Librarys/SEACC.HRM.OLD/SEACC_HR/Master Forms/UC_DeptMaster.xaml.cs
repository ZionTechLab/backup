        void btn_Save_Click(object sender, RoutedEventArgs e)
        {
            if (CheckValidity())
            {
                try
                {
                    #region Update
                    if (SEACC_Form.IsUpdateMode)
                    {
                        if (SEACC_Form.CheckPermisshion_ToUpdate())
                        {
                            #region Update
                            tbl_genMasDepartment oldRecord = tbl_genMasDepartment.Select(txtDepartmentID.Text.Trim(), clsSecurity.CompanyID, clsSecurity.BranchID);
                            if (oldRecord != null)
                            {
                                tbl_genMasDepartment detail = new tbl_genMasDepartment(clsSecurity.CompanyID, clsSecurity.BranchID, txtDepartmentID.Text, txtDeptName.Text, txtDivisionID.Tag.ToString(), txtAddress.Text, txtTelephone.Text, txtTelephone1.Text, txtExtension.Text, txtFax.Text, txtContactPerson.Tag.ToString(), txtDescription.Text, oldRecord.IsCanceled, oldRecord.UserID_Created, clsSecurity.UserIDLoged, oldRecord.UserID_Canceled, oldRecord.TerminalID_Created, clsSecurity.TerminalID, oldRecord.TerminalID_Canceled, oldRecord.Date_Created, clsSecurity.getServerDateTime(), oldRecord.Date_Canceled);
                                detail.Update();
                                SEACCMessageBox.Show(MessegeBoxType.Successfully_Updated);
                            }
                            #endregion
                        }
                    }
                    #endregion

                    #region Insert
                    else
                    {
                        if (SEACC_Form.isAutoGenaratedCode)
                            txtDepartmentID.Text = SEACC_Form.getAutoGeneratedCode();

                        tbl_genMasDepartment InsertData = new tbl_genMasDepartment(clsSecurity.CompanyID, clsSecurity.BranchID, txtDepartmentID.Text, txtDeptName.Text, txtDivisionID.Tag.ToString(), txtAddress.Text, txtTelephone.Text, txtTelephone1.Text, txtExtension.Text, txtFax.Text, txtContactPerson.Tag.ToString(), txtDescription.Text, false, clsSecurity.UserIDLoged, "Default", "Default", clsSecurity.TerminalID, "Default", "Default", clsSecurity.getServerDateTime(), clsSecurity.getServerDateTime(), clsSecurity.getServerDateTime());
                        InsertData.Insert();
                        SEACCMessageBox.Show(MessegeBoxType.Successfully_Created);

                        #endregion
                    }
                }
                catch (Exception ex)
                {
                    SEACCExeption.Show(ex);
                }
                finally
                {
                    RefreshGrid();
                    ClearFillds();
                }


            }
        }

