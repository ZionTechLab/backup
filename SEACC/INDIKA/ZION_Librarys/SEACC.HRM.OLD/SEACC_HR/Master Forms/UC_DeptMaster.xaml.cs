        #region Refresh Grid
        private void RefreshGrid()
        {
            try
            {
                dgr_Main.dt.Clear();
                foreach (tbl_genMasDepartment detail in tbl_genMasDepartment.SelectAll().Where(p => p.Department_ID != "default" && p.IsCanceled == false))
                {
                    dgr_Main.dt.Rows.Add(detail.Department_ID, detail.DepartmentName, detail.Address, (detail.Division_ID == "default") ? "-" : clsRef_Name.get_Division_Name(detail.Division_ID), detail.Telephone1, detail.Fax, (detail.Employee_ID_HOD == "default") ? "-" : clsRef_Name.get_EmployeeName(detail.Employee_ID_HOD), detail.Remarks);
                }
                dgr_Main.RefreshGrid();
            }
            catch (Exception ex)
            {
                SEACCExeption.Show(ex);
            }
        }
        #endregion

        #region CheckValidity

        private bool CheckValidity()
        {
            bool bStatus = false;
            if (CheckValidity_EmptyField())
            {
                if (CheckValidity_DuplicateFiled())
                    bStatus = true;
                if (!ChekValidity_DuplicateNames())
                    bStatus = false;
            }
            return bStatus;
        }
        private bool CheckValidity_EmptyField()
        {
            bool bStatus = true;
            if (!clsValidation.Validate_EmptyValue(txtDepartmentID))
            {
                bStatus = false;
            }

            if (!clsValidation.Validate_EmptyValue(txtDeptName))
            {
                bStatus = false;
            }

            return bStatus;

        }
        public bool CheckValidity_DuplicateFiled()
        {
            bool bStatus = true;
            if (!SEACC_Form.IsUpdateMode)
            {
                tbl_genMasDepartment detail = tbl_genMasDepartment.Select(txtDepartmentID.Text.Trim(), clsSecurity.CompanyID, clsSecurity.BranchID);
                if (detail != null)
                {
                    bStatus = false;
                    SEACCMessageBox.Show(MessegeBoxType.RecordAlreadyExist);
                }
            }

            return bStatus;
        }
        public bool CheckNumberValidity()
        {
            return true;
        }


        public bool ChekValidity_DuplicateNames()
        {
            bool bStatus = true;
            foreach (tbl_genMasDepartment detail1 in tbl_genMasDepartment.SelectAll().Where(p => p.DepartmentName == txtDeptName.Text && p.IsCanceled == false && p.Department_ID != txtDepartmentID.Text))
            {
                if (detail1 != null)
                {
                    bStatus = false;
                    SEACCMessageBox.Show(MessegeBoxType.FieldAlreadyExist, "Department Name");
                    break;
                }
            }
            return bStatus;
        }

        #endregion

        #region FillDetails
        private void fillDetails(string sID)
        {
            try
            {
                if (sID != null)
                {
                    tbl_genMasDepartment detail = tbl_genMasDepartment.Select(sID, clsSecurity.CompanyID, clsSecurity.BranchID);
                    if (detail != null)
                    {
                        SEACC_Form.IsUpdateMode = true;
                        txtDepartmentID.IsEnabled = false;
                        txtDepartmentID.Text = detail.Department_ID;
                        txtDepartmentID.Tag = detail.Department_ID;
                        txtDeptName.Text = detail.DepartmentName;
                        txtAddress.Text = detail.Address;
                        if (detail.Division_ID != "default")
                        {
                            txtDivisionID.Text = clsRef_Name.get_Division_Name(detail.Division_ID);
                            txtDivisionID.Tag = detail.Division_ID;
                        }
                        else
                        {
                            txtDivisionID.Text = "-";
                            txtDivisionID.Tag = detail.Division_ID;
                        }

                        txtTelephone.Text = detail.Telephone1;
                        txtTelephone1.Text = detail.Telephone1;
                        txtExtension.Text = detail.Extention;
                        txtFax.Text = detail.Fax;
                        if (detail.Employee_ID_HOD != "default")
                        {
                            txtContactPerson.Text = detail.Employee_ID_HOD + "-" + clsRef_Name.get_EmployeeName(detail.Employee_ID_HOD);
                            txtContactPerson.Tag = detail.Employee_ID_HOD;
                        }
                        else
                        {
                            txtContactPerson.Text = "-";
                            txtContactPerson.Tag = detail.Employee_ID_HOD;
                        }

                        txtDescription.Text = detail.Remarks;
                    }
                }
            }
            catch (Exception ex)
            {
                SEACCExeption.Show(ex);
            }
        }
        #endregion

        #region Grid Event
        private void grd_DeptMaster_MouseLeftButtonUp1(object sender, EventArgs e)
        {
            try
            {
                object item = dgr_Main.grdMain.SelectedItem;
                if (item != null)
                {
                    string GridID = (dgr_Main.grdMain.SelectedCells[0].Column.GetCellContent(item) as TextBlock).Text;
                    fillDetails(GridID);
                }
            }
            catch (Exception ex)
            {
                SEACCMessageBox.Show("Error", ex.Message, MessageBoxButton.OK);
            }
        }
