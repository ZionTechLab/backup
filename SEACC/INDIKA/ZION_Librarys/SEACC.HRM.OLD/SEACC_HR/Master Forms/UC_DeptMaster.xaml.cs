        void btn_Cancel_Click(object sender, RoutedEventArgs e)
        {
            try
            {
                if (SEACC_Form.IsUpdateMode)
                {
                    if (txtDepartmentID.Tag != null)
                    {
                        bool bMessegeBoxResult = SEACCMessageBox.Show(MessegeBoxType.Cancel_Confirmation);
                        if (bMessegeBoxResult)
                        {
                            tbl_genMasDepartment oDeleteDetails = tbl_genMasDepartment.Select(txtDepartmentID.Text.Trim(), clsSecurity.CompanyID, clsSecurity.BranchID);
                            if (oDeleteDetails != null)
                            {
                                oDeleteDetails.IsCanceled = true;
                                oDeleteDetails.TerminalID_Canceled = clsSecurity.TerminalID;
                                oDeleteDetails.UserID_Canceled = clsSecurity.UserIDLoged;
                                oDeleteDetails.Date_Canceled = clsSecurity.getServerDateTime();
                                oDeleteDetails.Update();
                                SEACCMessageBox.Show(MessegeBoxType.Successfully_Canceled);
                                ClearFillds();
                                RefreshGrid();
                            }
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                SEACCExeption.Show(ex);
            }
        }

