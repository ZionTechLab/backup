        #region Form Load
        public UC_WebLinks()
        {
            #region Initialize Usercontrol
            InitializeComponent(); 

            SEACC_Form.enmFormName = FormName.Web_Links;
            grd_PopUp.Visibility = Visibility.Hidden;
            SEACC_Form.Initialize();
            #endregion

            #region Initialize Data Table
