        #region Clear Fields
        private void ClearFields()
        {
            SEACC_Form.IsUpdateMode = false;
            cls_Formater.SetEnableDisable_ForigenKeyLabelTextBox(txtDistrictCode, true, false,false);
            cls_Formater.SetEnableDisable_ForigenKeyLabelTextBox(txtProvinceCode, true, false, false);
            cls_Formater.SetEnableDisable_LableTextbox(txtDistrictName, true, false,false);

            txtDistrictCode.Text = "";
            txtDistrictCode.Tag = null;
            txtDistrictName.Text = "";
            txtProvinceCode.Text = "";

            if (SEACC_Form.isAutoGenaratedCode)
            {
                txtDistrictCode.setReadOnlyStatus(true);
                txtDistrictCode.Text = "<Auto Generate>";
            }
            else
                txtDistrictCode.setReadOnlyStatus(false);
        }
        #endregion

        #region Check validity
        private bool CheckValidity()
        {
            bool bStatus = false;
            if (CheckValidity_EmptyField())
            {
                if (CheckValidity_DuplicateFiled())
                    bStatus = true;
            }
            return bStatus;
        }
        private bool CheckValidity_EmptyField()
        {
            bool bStatus = true;

            if (!clsValidation.Validate_EmptyValue(txtDistrictCode))
                bStatus = false;
            if (!clsValidation.Validate_EmptyValue(txtProvinceCode))
                bStatus = false;
            if (!clsValidation.Validate_EmptyValue(txtDistrictName))
                bStatus = false;

            return bStatus;
        }

        public bool CheckValidity_DuplicateFiled()
        {
            bool bStatus = true;
            if (!SEACC_Form.IsUpdateMode)
            {
                tbl_genMasDistrict oDetail = tbl_genMasDistrict.Select(txtDistrictName.Text);
                if (oDetail != null)
                {
                    bStatus = false;
                    SEACCMessageBox.Show(MessegeBoxType.RecordAlreadyExist);
                }
            }
            return bStatus;
        }
        #endregion

        #region Fill Details
        private void fillDetails(string sID)
        {
            try
            {
                if (sID != null)
                {
                    tbl_genMasDistrict FillDetails = tbl_genMasDistrict.Select(sID);
                    if (FillDetails != null)
                    {
                        SEACC_Form.IsUpdateMode = true;
                        txtDistrictCode.IsEnabled = false;
                        txtDistrictCode.Text = FillDetails.District_ID;
                        txtDistrictCode.Tag = FillDetails.District_ID;
                        txtProvinceCode.Text =clsRef_Name.get_Province_Name(FillDetails.Province_ID);
                        txtProvinceCode.Tag = FillDetails.Province_ID;
                        txtDistrictName.Text = FillDetails.DistrictName;

                    }
                }

            }
            catch (Exception ex)
            {
                SEACCExeption.Show(ex);
            }
        }
        #endregion

        #region Grid Event
        private void grd_District_MouseLeftButtonUp1(object sender, EventArgs e)
        {
            try
            {
                object item = dgr_Main.grdMain.SelectedItem;
                if (item != null)
                {
                    string GridID = (dgr_Main.grdMain.SelectedCells[0].Column.GetCellContent(item) as TextBlock).Text;
                    fillDetails(GridID);
                }
            }
            catch (Exception ex)
            {
                SEACCExeption.Show(ex);
            }
        }
        #endregion

