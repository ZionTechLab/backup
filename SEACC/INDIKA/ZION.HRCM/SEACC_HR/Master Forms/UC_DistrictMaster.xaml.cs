        #region Refresh Grid
        private void RefreshGrid()
        {
            try
            {
                dgr_Main.dt.Clear();
                foreach (tbl_genMasDistrict item in tbl_genMasDistrict.SelectAll().Where(p => p.District_ID != "default" && p.IsCanceled == false))
                {
                    dgr_Main.dt.Rows.Add(item.District_ID, clsRef_Name.get_Province_Name(item.Province_ID), item.DistrictName);
                }
                dgr_Main.RefreshGrid();
            }
            catch (Exception ex)
            {
                SEACCMessageBox.Show("Error", ex.Message, MessageBoxButton.OK);
            }
        }
