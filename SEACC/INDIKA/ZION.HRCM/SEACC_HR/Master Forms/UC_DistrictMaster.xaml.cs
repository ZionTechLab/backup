        void btn_Cancel_Click(object sender, RoutedEventArgs e)
        {
            if (SEACC_Form.IsUpdateMode)
            {
                if (txtDistrictCode.Tag != null)
                {
                    bool bMessegeBoxResult = SEACCMessageBox.Show(MessegeBoxType.Cancel_Confirmation);

                    if (bMessegeBoxResult)
                    {
                        tbl_genMasDistrict oDistrict = tbl_genMasDistrict.Select(txtDistrictCode.Text.Trim());
                        if (oDistrict != null)
                        {
                            oDistrict.IsCanceled = true;
                            oDistrict.Date_Canceled = clsSecurity.getServerDateTime();
                            oDistrict.TerminalID_Canceled = clsSecurity.TerminalID;
                            oDistrict.Update();
                            SEACCMessageBox.Show(MessegeBoxType.Successfully_Canceled);
                            ClearFields();
                            RefreshGrid();
                        }
                    }
                }
            }
        } 



