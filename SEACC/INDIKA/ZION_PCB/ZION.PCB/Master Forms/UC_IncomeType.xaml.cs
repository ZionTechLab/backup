        #region Clear Fields
        private void ClearFields()
        {
            SEACC_Form.IsUpdateMode = false;

            cls_Formater.SetEnableDisable_ForigenKeyLabelTextBox(txtIncomeTypeID, true, false, false);
            cls_Formater.SetEnableDisable_LableTextbox(txtIncomeTypeName, true, false, false);

            txtIncomeTypeID.Tag = null;

            txtIncomeTypeID.Text = "";
            txtIncomeTypeName.Text = "";

            if (SEACC_Form.isAutoGenaratedCode)
            {
                txtIncomeTypeID.setReadOnlyStatus(true);
                txtIncomeTypeID.Text = "<Auto Generate>";
            }
            else
                txtIncomeTypeID.setReadOnlyStatus(false);            

        }
        #endregion

        #region Refresh Grid
        private void RefreshGrid()
        {
            try
            {
                dgr_Main.dt.Clear();
                foreach (tbl_pcbRefIncomeType detail in tbl_pcbRefIncomeType.SelectAll().Where(p => p.PcbIncomeType_ID != "default" && !p.IsCanceled))
                {
                    dgr_Main.dt.Rows.Add(detail.PcbIncomeType_ID, detail.PcbIncomeTypeName);
                }
                dgr_Main.RefreshGrid();
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", clsSecurity.getFormID(SEACC_Form.enmFormName), ex);
                SEACCExeption.Show(ex);
            }
        }
        #endregion

        #region FillDetails
        private void fillDetails(string sID)
        {
            try
            {
                if (sID != null)
                {
                    tbl_pcbRefIncomeType detail = tbl_pcbRefIncomeType.Select(sID);
                    if (detail != null)
                    {
                        SEACC_Form.IsUpdateMode = true;
                        cls_Formater.SetEnableDisable_ForigenKeyLabelTextBox(txtIncomeTypeID, false, false, false);

                        txtIncomeTypeID.Text = detail.PcbIncomeType_ID;
                        txtIncomeTypeID.Tag = detail.PcbIncomeType_ID;
                        txtIncomeTypeName.Text = detail.PcbIncomeTypeName;                        
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", clsSecurity.getFormID(SEACC_Form.enmFormName), ex);
                SEACCExeption.Show(ex);
            }
        }
        #endregion        

        #region Search Events
        private void txtIncomeTypeID_MouseDoubleClick(object sender, MouseButtonEventArgs e)
        {
            frm_search RowDataSearch = new frm_search(false);
            RowDataSearch.WindowStartupLocation = WindowStartupLocation.CenterScreen;
            List<string> lstResult = RowDataSearch.Show(Digiteq_Logic.Search.PCB_IncomeType);

            if (RowDataSearch.DialogResult == true)
                fillDetails(lstResult[0]);

        }
        #endregion

        #region Grid Events
        private void dgr_Main_MouseLeftButtonUp1(object sender, EventArgs e)
        {
            try
            {
                object item = dgr_Main.grdMain.SelectedItem;
                if (item != null)
                {
                    string GridID = (dgr_Main.grdMain.SelectedCells[0].Column.GetCellContent(item) as TextBlock).Text;
                    fillDetails(GridID);
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", clsSecurity.getFormID(SEACC_Form.enmFormName), ex);
                SEACCMessageBox.Show("Error", ex.Message, MessageBoxButton.OK);
            }
        }
