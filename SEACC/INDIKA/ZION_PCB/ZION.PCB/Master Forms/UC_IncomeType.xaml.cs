        private void btn_Save_Click(object sender, RoutedEventArgs e)
        {
            if (CheckValidity())
            {
                try
                {
                    #region Update
                    if (SEACC_Form.IsUpdateMode)
                    {
                        if (SEACC_Form.CheckPermission_ToSave(true))
                        {
                            tbl_pcbRefIncomeType oOldType = tbl_pcbRefIncomeType.Select(txtIncomeTypeID.Tag.ToString());
                            if (oOldType != null)
                            {
                                if (!oOldType.IsCanceled)
                                {
                                    tbl_pcbRefIncomeType oType = new tbl_pcbRefIncomeType(txtIncomeTypeID.Tag.ToString(), txtIncomeTypeName.Text, oOldType.IsCanceled, oOldType.CreateUser_ID, clsSecurity.UserIDLoged, oOldType.CanceldUser_ID, oOldType.DateCreate, clsSecurity.getServerDateTime(), oOldType.DateCanceled, oOldType.CreateUserTerminal_ID, clsSecurity.TerminalID, oOldType.CanceledUserTerminal_ID);
                                    oType.Update();
                                    SEACCMessageBox.Show(MessegeBoxType.Successfully_Updated);
                                }
                                else
                                    SEACCMessageBox.Show("Can not Update..", "This Expenditure is already cancelled", MessageBoxButton.OK);
                            }
                        }
                    }
                    #endregion

                    #region Insert
                    else
                    {
                        if (SEACC_Form.CheckPermission_ToSave(false))
                        {
                            if (SEACC_Form.isAutoGenaratedCode)
                                txtIncomeTypeID.Tag = SEACC_Form.getAutoGeneratedCode();

                            tbl_pcbRefIncomeType oNewType = new tbl_pcbRefIncomeType(txtIncomeTypeID.Tag.ToString(), txtIncomeTypeName.Text, false, clsSecurity.UserIDLoged, "default", "default", clsSecurity.getServerDateTime(), clsValidation.defaultDateTime, clsValidation.defaultDateTime, clsSecurity.TerminalID, "default", "default");
                            oNewType.Insert();
                            SEACCMessageBox.Show(MessegeBoxType.Successfully_Created);
                        }
                    }
                    #endregion
                }
                catch (Exception ex)
                {
                    clsValidate.WriteErrorLog("", clsSecurity.getFormID(SEACC_Form.enmFormName), ex);
                    SEACCExeption.Show(ex);
                }
                finally
                {
                    ClearFields();
                    RefreshGrid();
                }
            }
        }

        private void btn_Cancel_Click(object sender, RoutedEventArgs e)
        {
            try
            {
                if (SEACC_Form.IsUpdateMode)
                {
                    if (txtIncomeTypeID.Tag != null)
                    {
                        bool bMessegeBoxResult = SEACCMessageBox.Show(MessegeBoxType.Cancel_Confirmation);

                        if (bMessegeBoxResult)
                        {
                            tbl_pcbRefIncomeType Details = tbl_pcbRefIncomeType.Select(txtIncomeTypeID.Tag.ToString());
                            if (Details != null)
                            {
                                Details.IsCanceled = true;
                                Details.DateCanceled = clsSecurity.getServerDateTime();
                                Details.CanceldUser_ID = clsSecurity.UserIDLoged;
                                Details.CanceledUserTerminal_ID = clsSecurity.TerminalID;
                                Details.Update();

                                SEACCMessageBox.Show(MessegeBoxType.Successfully_Canceled);
                                ClearFields();
                                RefreshGrid();
                            }
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", clsSecurity.getFormID(SEACC_Form.enmFormName), ex);
                SEACCExeption.Show(ex);
            }
        }

