                tbl_sasInquiry Inquiry = tbl_sasInquiry.Select(sInquiryID);
                if (Inquiry != null)
                {
                    Inquiry.IsSeattled = bIsSettle;
                    Inquiry.IsLocked = bLocked;
                    Inquiry.Update();
                }

            }
        }
