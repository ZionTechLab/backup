        #region Reduce VAT & NBT From GrandTotal
        public static decimal Reduce_VATnNBT_FromGrandTotal(decimal dGrandTotal, decimal dVATPasantage, decimal dNBTPasantage)
        {
            decimal dSubTotal = 0;
            decimal dWithNBTAmount = dGrandTotal * 100 / (100 + dVATPasantage);
            dSubTotal = dWithNBTAmount * 100 / (100 + dNBTPasantage);
            return dSubTotal;
        }
        #endregion

        #region Reduce VAT From GrandTotal
        public static decimal Reduce_VAT_FromGrandTotal(decimal dGrandTotal, decimal dVATPasantage)
        {
            decimal dWithNBTAmount = dGrandTotal * 100 / (100 + dVATPasantage);
            return dWithNBTAmount;
        }
        #endregion

        //Discount
        #region Reducce Discount From Item UnitPrice
        public static decimal ReduceDiscountPacentage_FromItemUnitPrice(decimal dItemUnitPrice, decimal dDiscountPercentage)
        {
            decimal dUnitPrice_AfterDiscount = (dItemUnitPrice * (100 - dDiscountPercentage)) / 100;
            return dUnitPrice_AfterDiscount;
        }
