        #region Set Settle Delivery Order
        public static void SetSettle_DeliveryOrder(string sDeliveryOrderID, CheckBox chkUnitPricing, bool bInvoiceMadeAleardy)
        {
            bool bIsSettle = false, bLocked = false;
            if (clsConfig.bAutoSettleHideDeliveryOrder)
            {
                List<tbl_sasDeliveryOrder_Detail> details = tbl_sasDeliveryOrder_Detail.SelectAllByDeliveryOrder_ID(sDeliveryOrderID);
                foreach (tbl_sasDeliveryOrder_Detail detail in details)
                {
                    bIsSettle = true;
                    if (chkUnitPricing.Checked)
                    {
                        if ((detail.QtySettle + detail.QtyReturned) < detail.Qty)
                        {
                            bIsSettle = false;
                            break;
                        }
                        if ((detail.QtySettle + detail.QtyReturned) > 0)
                            bLocked = true;
                    }
                    else
                    {
                        if ((detail.WeightSettle + detail.WeightReturned) < detail.Weight)
                        {
                            bIsSettle = false;
                            break;
                        }
                        if ((detail.WeightSettle + detail.WeightReturned) > 0)
                            bLocked = true;
                    }
                }

                tbl_sasDeliveryOrder DeliveryOrder = tbl_sasDeliveryOrder.Select(sDeliveryOrderID);
                if (DeliveryOrder != null)
                {
                    if (bInvoiceMadeAleardy)
                    {
                        if (!DeliveryOrder.IsSeattled)
                            DeliveryOrder.IsSeattled = bIsSettle;
                    }
                    else
                        DeliveryOrder.IsSeattled = bIsSettle;

                    DeliveryOrder.IsLocked = bLocked;
                    DeliveryOrder.Update();
                }
            }
        }
