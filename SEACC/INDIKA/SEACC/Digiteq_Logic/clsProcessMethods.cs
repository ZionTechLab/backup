        public static decimal GetCostPrice_ByCostType(string sItemCode , enum_CostPriceType costType)
        {
            decimal dRtn = 0;
            tbl_genItemMaster_Pricing item = tbl_genItemMaster_Pricing.Select(sItemCode);
            if (item != null)
            {
                switch (costType)
                {
                    case enum_CostPriceType.WeightedAverage:
                        dRtn = item.WeightedAverageCostPrice;
                        break;
                    case enum_CostPriceType.LIFO:
                        dRtn = item.LifoCostPrice;
                        break;
                    case enum_CostPriceType.FIFO:
                        dRtn = item.FifoCostPrice;
                        break;
                    case enum_CostPriceType.HighestPurchaseCost:
                        dRtn = item.HighestPurchaseCostPrice;
                        break;
                    case enum_CostPriceType.LovestPurchaseCost:
                        dRtn = item.LowestPurchaseCostPrice;
                        break;
                    case enum_CostPriceType.CostPrice1:
                        dRtn = item.CostPrice1;
                        break;
                    case enum_CostPriceType.CostPrice2:
                        dRtn = item.CostPrice2;
                        break;
                }
            }
            return dRtn;
        }
