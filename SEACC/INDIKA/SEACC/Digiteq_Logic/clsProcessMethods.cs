        #region Archive Chat
        public static void ArchiveChat(string sChatID)
        {
            List<tbl_utlChatUser> cUsers = tbl_utlChatUser.SelectAllByChat_ID(sChatID);
            if (cUsers.Count == 0)
            {
                tbl_utlChat chat = tbl_utlChat.Select(sChatID);
                if (chat != null)
                {
                    //Archive Chat Header
                    arc_tbl_utlChat aChat = new arc_tbl_utlChat(chat.Chat_ID, chat.StartTime, clsSecurity.getServerDateTime(), chat.CreateUser_ID);
                    aChat.Insert();

                    //Archive Chat Detail
                    List<tbl_utlChat_Message> cMessages = tbl_utlChat_Message.SelectAllByChat_ID(sChatID);
                    foreach (tbl_utlChat_Message cMessage in cMessages)
                    {
                        arc_tbl_utlChat_Message aMessage = new arc_tbl_utlChat_Message(sChatID, cMessage.User_ID, cMessage.ChatMessage, cMessage.SendTime);
                        aMessage.Insert();
                    }

                    //Delete Records
                    tbl_utlChat_Message.DeleteAllByChat_ID(sChatID);
                    chat.Delete();
                }
            }
        }
