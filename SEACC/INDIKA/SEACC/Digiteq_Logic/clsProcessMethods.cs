        private static bool ValidateInputItme(string sItem, decimal WeightInput, bool bIsPrePlan, ref List<clsExcludeItems> LstExItems)
        {
            bool bIsExclude = false;
            foreach (clsExcludeItems oEItems in LstExItems.Where(p => p.sItemID == sItem))
            {
                if (!bIsPrePlan)
                {
                    oEItems.dInputQty += WeightInput;
                    oEItems.bIsUsed = true;
                }
                bIsExclude = true;
            }
            return bIsExclude;
        }

