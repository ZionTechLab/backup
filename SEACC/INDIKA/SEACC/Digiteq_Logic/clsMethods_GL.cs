        public static DateTime GetDateFinancialYearDate(string FinantiolYear, string Month)
        {
            int iMonth = clsGenaralName.getMonthNumber(Month);

            DateTime Date = new DateTime();
            tbl_accFinancialYearMaster detail = tbl_accFinancialYearMaster.Select(FinantiolYear);
            if (detail != null && detail.FinancialYear_ID != "default")
            {
                DateTime DateEnd = detail.DateEnd;
                DateTime DateStart = detail.DateStart;
                int year = detail.DateStart.Year, i = 0;
                for (DateTime newDate = DateStart; newDate <= DateEnd; newDate = DateStart.AddMonths(i))
                {
                    if (newDate.Month == iMonth)
                    {
                        year = newDate.Year;
                        break;
                    }
                    i++;
                }
                Date = new DateTime(year, iMonth, 1);
            }
            return Date;
        }

