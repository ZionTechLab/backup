                return OldPostingID;
            }
            catch (Exception ex)
            {
                MessageBox.Show(ex.Message.ToString(), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Error);
                clsValidate.WriteErrorLog("", 0,ex);
                return OldPostingID;
            }
        }
