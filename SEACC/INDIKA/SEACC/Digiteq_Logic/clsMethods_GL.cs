        #region Update OPBL
        public static void Update_OPBL(string sFinYearTXN, string Accounts_Code, decimal Amount)
        {
            string sFinYearCurrent = getFinancialYear_ID_Current();
            string sFinYear_Opening_Month = accountTXNStartMonth();

            if (IsPnlAccount(Accounts_Code))
                Accounts_Code = clsConfig.sAccountNo_RetainedEarnings;

            while (sFinYearCurrent != sFinYearTXN)
            {
                sFinYearTXN = getFinancialYear_ID_Next(sFinYearTXN);

                tbl_accFinancialYearMaster_Month_OpenningBalance detail = tbl_accFinancialYearMaster_Month_OpenningBalance.Select(Accounts_Code, sFinYearTXN, sFinYear_Opening_Month);
                if (detail != null)
                {
                    decimal dOPBL = (detail.IsCreditOpening ? -1 : 1) * detail.OpeningBalance;
                    dOPBL += Amount;

                    detail.OpeningBalance = (dOPBL > 0 ? 1 : -1) * dOPBL;
                    detail.IsCreditOpening = (dOPBL > 0 ? false : true);
                    detail.Update();
                }
                else
                {
                    tbl_accFinancialYearMaster_Month FYM_detail = tbl_accFinancialYearMaster_Month.Select(sFinYearTXN, sFinYear_Opening_Month);
                    if (FYM_detail == null)
                    {
                        tbl_accFinancialYearMaster_Month Mdetail = new tbl_accFinancialYearMaster_Month(sFinYearTXN, sFinYear_Opening_Month, clsSecurity.getServerDateTime(), clsSecurity.getServerDateTime(), false, clsSecurity.UserIDLoged, clsSecurity.getServerDateTime(),
                             clsSecurity.UserIDLoged, clsSecurity.UserIDLoged,
                            clsSecurity.TerminalID, clsSecurity.TerminalID,
                            clsSecurity.getServerDateTime(), clsSecurity.getServerDateTime());
                        Mdetail.Insert();
                    }
                    tbl_accFinancialYearMaster_Month_OpenningBalance oOPBL = new tbl_accFinancialYearMaster_Month_OpenningBalance(Accounts_Code, sFinYearTXN, sFinYear_Opening_Month, Amount * (Amount > 0 ? 1 : -1), (Amount > 0 ? false : true), 0, false, 0, 0, 0);
                    oOPBL.Insert();
                }
            }
        }
