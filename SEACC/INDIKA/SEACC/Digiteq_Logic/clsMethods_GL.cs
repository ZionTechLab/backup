                            Update_Secondary_TXN(iLineNo++, sGLPostingID, sSlotID, oSalesNoteType.Gl_ID, "default", "default", oTxn.Customer_ID, "default", "default", "default", "-", oTxn.CreditNote_ID, oTxn.CreditNote_ID, oTxn.CreditNoteDate, sNarration, (dSubTotal - dDiscountTotal), false, "", sCustomer, oTxn.CompanyBranch_ID);
