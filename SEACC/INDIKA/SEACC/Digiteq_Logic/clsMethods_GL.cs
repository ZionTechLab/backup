        public static bool GLPosting_Delete(string sPostingID)
        {
            bool sCompleted = false;
            try
            {
          

                tbl_accGLPosting oPosting = tbl_accGLPosting.Select(sPostingID);
                if (oPosting != null)
                {
                    string sFinYearTXN = getFinancialYear_ID(oPosting.TransactionDate);

                    foreach (tbl_accGLPosting_Detail detail in tbl_accGLPosting_Detail.SelectAllByGlPosting_ID(sPostingID))
                    {
                        if (detail.IsCredit)
                            detail.Amount= detail.Amount * -1;

                        Update_OPBL(sFinYearTXN, detail.Gl_ID, -detail.Amount);
                        detail.Delete();
                    }
                    oPosting.Delete();
                    sCompleted = true;
                }

                return sCompleted;
            }
