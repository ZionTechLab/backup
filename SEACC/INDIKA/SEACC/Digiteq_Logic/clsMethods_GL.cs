        public static string Update_Primary_TXN(string OldPostingID, int Slot_ID, string Transaction_ID, DateTime Transaction_Date, string Customer_ID, string Supplier_ID, string sRemarks)
        {
            try
            {
                bool isUpdate = true;
                tbl_accGLPosting oldRecord = tbl_accGLPosting.Select(OldPostingID);
                if (oldRecord != null && oldRecord.GlPosting_ID != "default")
                {
                    tbl_accGLPosting detail = new tbl_accGLPosting(oldRecord.GlPosting_ID, oldRecord.Batch_ID, oldRecord.Slot_ID, oldRecord.Transaction_ID, Transaction_Date, Customer_ID, Supplier_ID, sRemarks, oldRecord.CreateUser_ID, oldRecord.CreateTerminal_ID, oldRecord.DateCreate, oldRecord.CompanyID, oldRecord.CompanyBranch_ID);
