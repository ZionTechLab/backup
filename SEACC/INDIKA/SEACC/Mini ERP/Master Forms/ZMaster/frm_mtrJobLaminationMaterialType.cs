        #region Datagrid Format
        private void CusDataGridViewFormat()
        {
            clsFormatter.ApplyGridFormat(dgvDetail);
        }
        #endregion

        #region Clear Fields
        private void ClearFields()
        {

            //set the flag and enble the id

            IsUpdate = false;
            clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtJobLaminationMaterialTypeID, true);
            clsCommon.SetEnableDisable_NormalLabel(lblClassID, true);

            txtJobLaminationMaterialTypeName.Clear();
            txtDencity.Clear();

           if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                txtJobLaminationMaterialTypeID.Text = "<Auto Generate>";
           else
                txtJobLaminationMaterialTypeID.Clear();

            if (txtJobLaminationMaterialTypeID.Enabled)
            {
                txtJobLaminationMaterialTypeID.SelectAll();
                txtJobLaminationMaterialTypeID.Focus();
            }
            //txtClassID.Text = "ok";
        }
        #endregion

        #region Refresh Grid
        private void RefreshGrid()
        {
            int iRow;
            dgvDetail.Rows.Clear();
            List<tbl_zJobLaminationMaterialType> details = tbl_zJobLaminationMaterialType.SelectAll();
            foreach (tbl_zJobLaminationMaterialType detail in details)
            {
                if (detail.LaminationMaterailType_ID.Trim() != "default")
                {
                    dgvDetail.Rows.Add();
                    iRow = dgvDetail.Rows.Count - 1;
                    dgvDetail["CategoryID", iRow].Value = detail.LaminationMaterailType_ID;
                    dgvDetail["CategoryName", iRow].Value = detail.LaminationMaterailTypeName;
                    dgvDetail["Prifix", iRow].Value =clsFormatter.FormatToNumberWithOneDecimalPlaces(detail.Dencity);
                }
            }
        }
        #endregion

        #region Fill Details
        private void FillDetails(string sID)
        {
            if (sID.Length > 0)
            {
                tbl_zJobLaminationMaterialType detail = tbl_zJobLaminationMaterialType.Select(sID);
                if (detail != null)
                {
                    //set the update flag and Locked
                    IsUpdate = true;
                    clsCommon.SetEnableDisable_PrimaryKeyTextbox(txtJobLaminationMaterialTypeID, false);
                    clsCommon.SetEnableDisable_NormalLabel(lblClassID, false);

                    //asign values
                    txtJobLaminationMaterialTypeID.Text = detail.LaminationMaterailType_ID;
                    txtJobLaminationMaterialTypeName.Text = detail.LaminationMaterailTypeName;
                    txtDencity.Text = detail.Dencity.ToString();
                }
            }
        }
        #endregion


        #region Check Validity
        private bool CheckValidity()
        {
            string strMessage = "";
            bool bStatus = true;

            if (txtJobLaminationMaterialTypeName.TextLength == 0)
            {
                strMessage += "\n" + "Lamination Material Type Name";
                bStatus = false;
            }
            if (txtDencity.TextLength == 0)
            {
                strMessage += "\n" + "Dencity Name ";
                bStatus = false;
            }
            if (bStatus == false)
            {
                MessageBox.Show(clsFormatter.getCommonStatusStripMessage(StatusStripMessageTypes.WhenInsert, strMessage), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            return bStatus;
        }

