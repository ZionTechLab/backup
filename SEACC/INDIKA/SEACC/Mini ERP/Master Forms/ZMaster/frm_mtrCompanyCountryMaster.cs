        #region Form Load
        public frm_mtrCompanyCountryMaster()
        {
            sFormConfigCode = clsAutocode.getFormConfigCode(FormName.ZBranch);
            iFormID = clsSecurity.getFormID(FormName.ZBranch);
            if (!clsSecurity.PermissionToRead(clsSecurity.UserIDLoged, iFormID))
            {
                bNoAccess = true;
            }
            InitializeComponent();
        }

        private void frm_mtrBranch_Load(object sender, EventArgs e)
        {
            
            
            //add data to the datagrid and format
            RefreshGrid();
            CusDataGridViewFormat();
            ClearFields();
        }
