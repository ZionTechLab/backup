        private bool CheckNumberValidityDeposit()
        {
            string strMessage = "";
            bool bStatus = true;

            try
            {
                if (!clsCommon.isCurrency(txtCountChequeSelected.Text.Trim()))
                {
                    strMessage += "\n Selected Cheque Count";
                    bStatus = false;
                }
                if (!clsCommon.isCurrency(txtAmountChequeSelected.Text.Trim()))
                {
                    strMessage += "\n Selected Cheque Amount";
                    bStatus = false;
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID, ex);
                SEACCException.Show(ex);
            }

            if (bStatus == false)
                MessageBox.Show(clsFormatter.getCommonStatusStripMessage(StatusStripMessageTypes.WhenInserNumber, strMessage), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);

            return bStatus;
        }
        private bool CheckValidity_ChequeDepositPosting()
        {
            bool bStatus = false;
            if (clsConfig.bAutoPostingEnable)
            {
                bool bSlotStatus_Bank = clsMethods_GL.CheckAccountLink_Bank(txtDepositAccountNo.Text);
                bool bSlotStatus_ChequeDeposit = clsMethods_GL.CheckAccountLink(AccSlot.ChequeDeposit, true);
                bool bSlotStatus_ChequeREDeposit = clsMethods_GL.CheckAccountLink(AccSlot.ChequeReDeposit, true);

                if (bSlotStatus_Bank && bSlotStatus_ChequeDeposit && bSlotStatus_ChequeREDeposit)
                    bStatus = true;
            }
            else
                bStatus = true;
            return bStatus;
        }

