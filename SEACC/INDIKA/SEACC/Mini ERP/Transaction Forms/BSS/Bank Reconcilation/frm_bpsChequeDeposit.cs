        private void dgvDetail_CellMouseClick(object sender, DataGridViewCellMouseEventArgs e)
        {
            if (e.RowIndex >= 0)
            {
                string sColName = "";
                if (e.ColumnIndex >= 0)
                    sColName = dgvDetail.Columns[e.ColumnIndex].Name;

                if (sColName == "RegisterCode" || sColName == "RTSRegisterCode")
                {
                    string sRegisterID = dgvDetail[e.ColumnIndex, e.RowIndex].Value.ToString();
                    tbl_bpsChequeRegister detail = tbl_bpsChequeRegister.Select(sRegisterID);
                    if (detail != null)
                    {
                        frm_bpsChequeViewer cheque = new frm_bpsChequeViewer();
                        cheque.glbChequeRegisterID = detail.ChequeRegister_ID;
                        cheque.ShowDialog();
                    }
                }

                else if (sColName == "ReceiptID" || sColName == "RTSReceiptID")
                {
                    string sReceiptID = dgvDetail[e.ColumnIndex, e.RowIndex].Value.ToString();
                    tbl_bpsReceipt detail = tbl_bpsReceipt.Select(sReceiptID);
                    if (detail != null)
                    {
                        if (detail.IsSalesReceipt)
                        {
                            UC_bpsReceiptSales cheque = new UC_bpsReceiptSales(FormName.UCReceipt);
                          
                            cheque.glbReceiptID = detail.Receipt_ID;
                            clsHelpMethods_Local.DisplayForm(cheque, clsFormatter.colorBills, (this.Parent as Form).MdiParent);
                            //cheque.ShowDialog();
                        }
                        else
                        {
                            // frm_bpsReceipt_Interim cheque = new frm_bpsReceipt_Interim();
                            // cheque.gReceiptID = detail.Receipt_ID;
                            // cheque.ShowDialog();
                        }
                    }
                }
                else if (sColName == "IsSelected")
                {
                    bool bstatus = clsValidate.ValidateGridValue(dgvDetail, "IsSelected", e.RowIndex, false);
                    // if (bstatus)
                    dgvDetail[e.ColumnIndex, e.RowIndex].Value = !bstatus;

                    calculateSelectedCheques();
                }
            }
        }

        private void calculateSelectedCheques()
        {

            int iCount = 0;
            decimal dAmount = 0;
            foreach (DataGridViewRow row in dgvDetail.Rows)
            {
                try
                {
                    if (dgvDetail["IsSelected", row.Index].Value != null && dgvDetail["IsSelected", row.Index].Value.ToString().Length > 0)
                    {
                        if (bool.Parse(dgvDetail["IsSelected", row.Index].Value.ToString()) == true)
                        {
                            iCount++;
                            if (dgvDetail["Amount", row.Index].Value != null && dgvDetail["Amount", row.Index].Value.ToString().Length > 0 && clsCommon.isCurrency(dgvDetail["Amount", row.Index].Value.ToString()))
                                dAmount += decimal.Parse(dgvDetail["Amount", row.Index].Value.ToString());
                        }
                    }
                }
                catch (Exception ex)
                {
                    clsValidate.WriteErrorLog("", iFormID, ex);
                    SEACCException.Show(ex);
                }
            }
            txtAmountChequeSelected.Text = clsFormatter.FormatToCurrecyWithThousendSep(dAmount);
            txtCountChequeSelected.Text = iCount.ToString();
        }

        #region Selected Chques Count
        private bool CheckSelectedChequeCount()
        {
            bool bStatus = true, bSelected = false;
            int ValiedRowCount = 0;

            foreach (DataGridViewRow row in dgvDetail.Rows)
            {
                DateTime sTxnDate = clsValidate.ValidateGridValue(dgvDetail, "dateCheque", row.Index, DateTime.Now);
                 bSelected = clsValidate.ValidateGridValue(dgvDetail, "IsSelected", row.Index, false);
                if (bSelected)
                {
                    if (bActiveDateValidation)
                    {
                        if (sTxnDate.Date <= dtpDepositDate.Value.Date)
                        {
                            ValiedRowCount++;
                        }
                        else
                        {
                            MessageBox.Show("Invalied Deposit     date......!", "Validation Error");
                            return false;
                        }
                    }
                    else
                        ValiedRowCount++;
                }
                if (ValiedRowCount == 0)
                    bStatus = false;

            }
            return bStatus;
        }
