            this.DialogResult = DialogResult.Abort;
        }

        public bool Show(bool isInwordCheque, string TxnID, string ChequeRegisterID, string StatusID, string TxnType)
        {
            bIsInwordCheque = isInwordCheque;
            sTxnID = TxnID;
            sChequeRegisterID = ChequeRegisterID;
            sStatusID = StatusID;
            sTxnType = TxnType;
            this.ShowDialog();

            return bIsCancel;
        }

