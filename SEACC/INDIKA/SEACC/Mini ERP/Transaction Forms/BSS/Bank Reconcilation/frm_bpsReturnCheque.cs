                                                                clsSecurity.UserIDLoged, clsSecurity.UserIDLoged, "default", "default", clsSecurity.UserIDLoged, clsSecurity.UserIDLoged,
                                                                clsSecurity.TerminalID, clsSecurity.TerminalID, clsSecurity.TerminalID, clsSecurity.TerminalID,
                                                                clsSecurity.getServerDateTime(), clsSecurity.getServerDateTime(), clsSecurity.getServerDateTime(), clsSecurity.getServerDateTime(), clsSecurity.getServerDateTime(), clsSecurity.getServerDateTime(),
                                                                true, false, false, false, false, false, false, false, false, 0, false,
                                                                oCheque.ChequeRegister_ID, true, 0, clsSecurity.CompanyID, clsSecurity.BranchID);
                                            AccAPN.Insert();

                                            //clsDB.update_CustomerReturnedCheques(oCheque.Customer_ID, oCheque.Amount, oCheque.AccountNumber);
                                            //clsDB.update_CustomerDeposittedChequesFromReturns(oCheque.Customer_ID, oCheque.Amount, oCheque.AccountNumber);

