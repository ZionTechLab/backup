        private void dgvAPN_MouseUp(object sender, MouseEventArgs e)
        {
            if (dgvAPN.RowCount > 0)
            {
                string sTxnId = dgvAPN.SelectedRows[0].Cells[1].Value.ToString();
                string sTxnType = dgvAPN.SelectedRows[0].Cells[0].Value.ToString();
                string lineNo = "0";
                try
                {
                    lineNo = dgvAPN.SelectedRows[0].Cells[1].Tag.ToString();
                }
                catch (Exception)
                {
                }

                string text = sTxnType + "," + dgvAPN.CurrentCell.RowIndex + "," + sTxnId + "," + lineNo;
                if (text != null)
                    dgvAPN.DoDragDrop(text, DragDropEffects.Move);
            }
        }

