        #region calculate APN
        private void calculate()
        {
            try
            {
                dtJornalEntry_CR.Rows.Clear();
                dtAPN.Rows.Clear();

                dtPV.Rows.Clear();
                dtDebitNote.Rows.Clear();
                dtJornalEntry_DB.Rows.Clear();

                #region CR
                decimal dInvoiceTotal = 0;
                foreach (Control con in zpnlSelettedAPN.Controls)
                {
                    if (con is TextBox && con.Visible == true)
                    {
                        string[] sData = con.Tag.ToString().Split(',');

                        #region Apn
                        if (sData[0] == "APN")
                        {
                            tbl_accAccountPayableNote oApn = tbl_accAccountPayableNote.Select(sData[2]);
                            if (oApn != null)
                            {
                                dInvoiceTotal += (oApn.GrandTotal - oApn.SettledAmount);
                                dtAPN.Rows.Add(oApn.AccountPayableNote_ID, oApn.BillNo, oApn.GrandTotal, oApn.GrandTotal - oApn.SettledAmount);
                            }
                        }
                        #endregion
                        #region Adj
                        else if (sData[0] == "Adj")
                        {
                            tbl_accJournalEntry_Detail oJED = tbl_accJournalEntry_Detail.SelectAllByJournalEntry_ID(sData[2]).Where(p => p.Line_No == int.Parse(sData[3])).FirstOrDefault();
                            if (oJED != null)
                            {
                                dInvoiceTotal += (oJED.Amount - oJED.SeattleAmount);
                                dtJornalEntry_CR.Rows.Add(oJED.JournalEntry_ID, oJED.Line_No, oJED.Amount, oJED.Amount - oJED.SeattleAmount);
                            }
                        }
                        #endregion
                    }
                }

                try
                {
                    pgrAPN.Value = int.Parse(dInvoiceTotal.ToString());
                }
                catch (Exception)
                {
                    pgrAPN.Value = pgrAPN.Maximum;
                }
                #endregion

                #region DB
                decimal dChequeTotal = 0;
                foreach (Control con in zpnlSettledPayment.Controls)
                {
                    if (con is TextBox && con.Visible == true)
                    {
                        string[] sData = (con.Tag.ToString().Split(','));

                        #region PV
                        if (sData[0] == "PV")
                        {
                            tbl_accPaymentVoucher oPv = tbl_accPaymentVoucher.Select(sData[2]);
                            if (oPv != null)
                            {
                                dChequeTotal += (oPv.TotalAmount - oPv.SettledAmount);
                                dtPV.Rows.Add(oPv.PaymentVoucher_ID, oPv.TotalAmount, oPv.TotalAmount - oPv.SettledAmount);
                            }
                        }
                        #endregion
                        #region DBN
                        else if (sData[0] == "DBN")
                        {
                            tbl_accDebitNote oDbn = tbl_accDebitNote.Select(sData[2]);
                            if (oDbn != null)
                            {
                                dChequeTotal += (oDbn.GrandTotal - oDbn.SettledAmount);
                                dtDebitNote.Rows.Add(oDbn.DebitNote_ID, oDbn.GrandTotal, oDbn.GrandTotal - oDbn.SettledAmount);
                            }
                        }
                        #endregion
                        #region JE
                        else if (sData[0] == "Adj")
                        {
                            tbl_accJournalEntry_Detail oJED = tbl_accJournalEntry_Detail.SelectAllByJournalEntry_ID(sData[2]).Where(p => p.Line_No == int.Parse(sData[3])).FirstOrDefault();
                            if (oJED != null)
                            {
                                dChequeTotal += (oJED.Amount - oJED.SeattleAmount);
                                dtJornalEntry_DB.Rows.Add(oJED.JournalEntry_ID, oJED.Line_No, oJED.Amount, oJED.Amount - oJED.SeattleAmount);
                            }
                        }
                        #endregion
                    }
                }
                try
                {
                    pgrPayment.Value = int.Parse(dChequeTotal.ToString());
                }
                catch (Exception)
                {
                    pgrPayment.Value = pgrPayment.Maximum;
                }
                #endregion

                lblAPNAmount.Text = clsFormatter.FormatToCurrecyWithThousendSep(dInvoiceTotal);
                lblPaymentAmount.Text = clsFormatter.FormatToCurrecyWithThousendSep(dChequeTotal);

                #region Calculate balances
                decimal dInvoice = 0, dPayament = 0, dBalance = 0;
                try
                {
                    if (lblAPNAmount.TextLength > 0)
                        dInvoice = decimal.Parse(lblAPNAmount.Text.Trim());
                    if (lblPaymentAmount.TextLength > 0)
                        dPayament = decimal.Parse(lblPaymentAmount.Text.Trim());
                }
                catch (Exception) { }
                dBalance = dPayament - dInvoice;
                txtBalance.Text = clsFormatter.FormatToCurrecyWithThousendSep(dBalance);
                #endregion

                FillDetail();
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID, ex);
                SEACCException.Show(ex);
            }
        }
