        #region Load Details
        private void LoadDetail()
        {
            if (txtSupplierID.Tag != null && txtSupplierID.Tag.ToString().Trim().Length > 0)
            {
                ClearSelections();

                LoadAPN(txtSupplierID.Tag.ToString());
                LoadPaymentVouchers(txtSupplierID.Tag.ToString());
                LoadDebitNotes(txtSupplierID.Tag.ToString());
                LoadAdjustments(txtSupplierID.Tag.ToString());

                dgvAPN.Sort(dgvAPN.Columns["Date"], ListSortDirection.Descending);
                dgvPV.Sort(dgvPV.Columns["PVDate"], ListSortDirection.Descending);
            }
        }

        #region Load APN
        private void LoadAPN(string sSupplierID)
        {
            int iAmount = 0;
            try
            {
                foreach (tbl_accAccountPayableNote detail in tbl_accAccountPayableNote.SelectAllBySupplier_ID(sSupplierID).Where(p => p.AccountPayableNoteDate.Date >= dtpFromDate.Value.Date && p.AccountPayableNoteDate.Date <= dtpToDate.Value.Date && p.AccountPayableNote_ID != "default" && !p.IsDeleted && !p.IsSeattled))
                {
                    this.dgvAPN.Rows.Add();
                    int rowIndex = this.dgvAPN.Rows.Count - 1;
                    this.dgvAPN["Txn", rowIndex].Value = "APN";
                    this.dgvAPN["TxnID", rowIndex].Value = detail.AccountPayableNote_ID;
                    this.dgvAPN["refNo", rowIndex].Value = detail.BillNo;
                    this.dgvAPN["Date", rowIndex].Value = detail.AccountPayableNoteDate;
                    this.dgvAPN["Amount", rowIndex].Value = (detail.GrandTotal - detail.SettledAmount);

                    iAmount += (int)detail.GrandTotal;
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID, ex);
                SEACCException.Show(ex);
            }
            this.pgrAPN.Maximum = iAmount;
            this.pgrPayment.Maximum = iAmount;
        }
        #endregion

        #region Load PaymentVouchers
        private void LoadPaymentVouchers(string sSupplierID)
        {
            try
            {
                foreach (tbl_accPaymentVoucher detail in tbl_accPaymentVoucher.SelectAllBySupplier_ID(sSupplierID).Where(p => p.PaymentVoucherDate.Date >= dtpFromDate.Value.Date && p.PaymentVoucherDate.Date <= dtpToDate.Value.Date && p.PaymentVoucher_ID != "default" && !p.IsDeleted && !p.IsSeattled))
                {
                    this.dgvPV.Rows.Add();
                    int rowIndex = this.dgvPV.Rows.Count - 1;
                    this.dgvPV["TxnPv", rowIndex].Value = "PV";
                    this.dgvPV["TxnIDPV", rowIndex].Value = detail.PaymentVoucher_ID;
                    this.dgvPV["PVDate", rowIndex].Value = detail.PaymentVoucherDate;
                    this.dgvPV["PVAmount", rowIndex].Value = (detail.TotalAmount - detail.SettledAmount);
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID, ex);
                SEACCException.Show(ex);
            }
        }
        #endregion

        #region Load JV
        private void LoadAdjustments(string sSupplierID)
        {
            try
            {
                foreach (tbl_accJournalEntry_Detail detailJED in tbl_accJournalEntry_Detail.SelectAllBySupplier_ID(sSupplierID).Where(p => p.Supplier_ID != "default" && !p.IsSeattled))
                {
                    tbl_accJournalEntry detail = tbl_accJournalEntry.Select(detailJED.JournalEntry_ID);
                    if (detail != null && detail.JournalEntryDate.Date >= dtpFromDate.Value.Date && detail.JournalEntryDate.Date <= dtpToDate.Value.Date && !detail.IsDeleted)
                    {
                        if (detailJED.IsCredit)
                        {
                            this.dgvAPN.Rows.Add();
                            int rowIndex = this.dgvAPN.Rows.Count - 1;
                            this.dgvAPN["Txn", rowIndex].Value = "Adj";
                            this.dgvAPN["TxnID", rowIndex].Value = detail.JournalEntry_ID;
                            this.dgvAPN["TxnID", rowIndex].Tag = detailJED.Line_No;
                            this.dgvAPN["refNo", rowIndex].Value = " - ";
                            this.dgvAPN["Date", rowIndex].Value = detail.JournalEntryDate;
                            this.dgvAPN["Amount", rowIndex].Value = (detailJED.Amount - detailJED.SeattleAmount);
                        }
                        else
                        {
                            this.dgvPV.Rows.Add();
                            int rowIndex = this.dgvPV.Rows.Count - 1;
                            this.dgvPV["TxnPv", rowIndex].Value = "Adj";
                            this.dgvPV["TxnIDPV", rowIndex].Value = detail.JournalEntry_ID;
                            this.dgvPV["TxnIDPV", rowIndex].Tag = detailJED.Line_No;
                            this.dgvPV["PVDate", rowIndex].Value = detail.JournalEntryDate;
                            this.dgvPV["PVAmount", rowIndex].Value = (detailJED.Amount - detailJED.SeattleAmount);
                        }
                    }
                }
            }

            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID, ex);
                SEACCException.Show(ex);
            }
        }
        #endregion

