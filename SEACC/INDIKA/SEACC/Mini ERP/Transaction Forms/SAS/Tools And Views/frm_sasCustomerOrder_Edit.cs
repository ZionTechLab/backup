        #region Get Qty/Weight Methods
        private decimal getDeliveryOrder_Qty(string sCustomerOrderID, string sItemID, string sSubCategory1, string sSubCateogry2, string sSerial1, string sSerial2)
        {
            decimal dQty = 0;
            try
            {
                List<tbl_sasDeliveryOrder_Detail> details = tbl_sasDeliveryOrder_Detail.SelectAllByCustomerOrder_ID(sCustomerOrderID);
                foreach (tbl_sasDeliveryOrder_Detail detail in details)
                {
                    if (detail.Item_ID == sItemID && detail.ItemSubCategory_ID == sSubCategory1 && detail.ItemSubCategory2_ID == sSubCateogry2 && detail.ItemSerialNo == sSerial1 && detail.ItemSerialNo2 == sSerial2)
                    {
                        dQty += detail.Qty;
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
            return dQty;
        }
        private decimal getDeliveryOrder_Weight(string sCustomerOrderID, string sItemID, string sSubCategory1, string sSubCateogry2, string sSerial1, string sSerial2)
        {
            decimal dWeight = 0;
            try
            {
                List<tbl_sasDeliveryOrder_Detail> details = tbl_sasDeliveryOrder_Detail.SelectAllByCustomerOrder_ID(sCustomerOrderID);
                foreach (tbl_sasDeliveryOrder_Detail detail in details)
                {
                    if (detail.Item_ID == sItemID && detail.ItemSubCategory_ID == sSubCategory1 && detail.ItemSubCategory2_ID == sSubCateogry2 && detail.ItemSerialNo == sSerial1 && detail.ItemSerialNo2 == sSerial2)
