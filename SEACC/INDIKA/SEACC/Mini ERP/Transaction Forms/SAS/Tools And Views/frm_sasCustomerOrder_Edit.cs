        #region Refresh
        private void RefreshGrid(string sID)
        {
            try
            {
                int iRow;
                decimal dDOQty = 0, dDOWeight = 0, dInvoiceQty = 0, dInvoiceWeight = 0;                
                dgvDetail.Rows.Clear();
                tbl_sasCustomerOrder cOrder = tbl_sasCustomerOrder.Select(sID);
                if (cOrder != null)
                {

                    List<tbl_sasCustomerOrder_Detail> details = tbl_sasCustomerOrder_Detail.SelectAllByCustomerOrder_ID(sID);
                    foreach (tbl_sasCustomerOrder_Detail detail in details)
                    {
                        //tbl_sasDeliveryOrder_Detail DO = tbl_sasDeliveryOrder_Detail.SelectAllByItem_ID(detail.Item_ID);

                        if (detail.CustomerOrder_ID.Trim() != "default")
                        {
                            dgvDetail.Rows.Add();
                            iRow = dgvDetail.Rows.Count - 1;
                            dgvDetail["ItemCode", iRow].Value = detail.Item_ID;
                            dgvDetail["ItemName", iRow].Value = clsGenaralName.getName_Item(detail.Item_ID);
                            dgvDetail["ItemSubCategoryID", iRow].Tag = detail.ItemSubCategory_ID;
                            dgvDetail["ItemSubCategoryID2", iRow].Tag = detail.ItemSubCategory2_ID;
                            dgvDetail["ItemSubCategoryID", iRow].Value = detail.ItemSubCategory_ID;
                            dgvDetail["ItemSubCategoryID2", iRow].Value = detail.ItemSubCategory2_ID;
                            dgvDetail["ItemSerialNo", iRow].Value = detail.ItemSerialNo;
                            dgvDetail["ItemSerialNo2", iRow].Value = detail.ItemSerialNo2;
                            dgvDetail["InquiryID", iRow].Value = detail.Inquiry_ID;
                            dgvDetail["Remarks", iRow].Value = detail.Remark;
                            dgvDetail["UOM", iRow].Value = clsGenaralName.getName_ItemUOM(detail.Item_ID);
                            dgvDetail["Quantity", iRow].Value = clsFormatter.FormatToNumberNoDecimal(detail.Qty);
                            dgvDetail["Weight", iRow].Value = clsFormatter.FormatToNumberNoDecimal(detail.Weight);

                            dDOQty = getDeliveryOrder_Qty(sID, detail.Item_ID, detail.ItemSubCategory_ID, detail.ItemSubCategory2_ID, detail.ItemSerialNo, detail.ItemSerialNo2);
                            dDOWeight = getDeliveryOrder_Weight(sID, detail.Item_ID, detail.ItemSubCategory_ID, detail.ItemSubCategory2_ID, detail.ItemSerialNo, detail.ItemSerialNo2);
                            dInvoiceQty = getInvoice_Qty(sID, detail.Item_ID, detail.ItemSubCategory_ID, detail.ItemSubCategory2_ID, detail.ItemSerialNo, detail.ItemSerialNo2);
                            dInvoiceWeight = getInvoice_Weight(sID, detail.Item_ID, detail.ItemSubCategory_ID, detail.ItemSubCategory2_ID, detail.ItemSerialNo, detail.ItemSerialNo2);
                            dgvDetail["QuantityDO", iRow].Value = clsFormatter.FormatToNumberNoDecimal(dDOQty);
                            dgvDetail["WeightDO", iRow].Value = clsFormatter.FormatToNumberNoDecimal(dDOWeight);
                            dgvDetail["QuantityInvoice", iRow].Value = clsFormatter.FormatToNumberNoDecimal(dInvoiceQty);
                            dgvDetail["WeightInvoice", iRow].Value = clsFormatter.FormatToNumberNoDecimal(dInvoiceWeight);
                            if (cOrder.IsWeightCalculation)
                            {
                                dgvDetail["EditWeight", iRow].Value = clsFormatter.FormatToNumberNoDecimal(getEditValue(detail.Weight, dDOWeight, dInvoiceWeight));
                                dgvDetail["EditQuantity", iRow].Value = 0;                                
                            }
                            else
                            {
                                dgvDetail["EditQuantity", iRow].Value = clsFormatter.FormatToNumberNoDecimal(getEditValue(detail.Qty, dDOQty, dInvoiceQty));
                                dgvDetail["EditWeight", iRow].Value = 0;
                            }
                        }
                    }
                }                
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
