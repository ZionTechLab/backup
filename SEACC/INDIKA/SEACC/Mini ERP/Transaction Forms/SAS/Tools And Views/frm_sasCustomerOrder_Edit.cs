        #region Btn Save
        private void btnSave_Click(object sender, EventArgs e)
        {
            if (CheckValidity())
            {
                if (CheckNumberValidity())
                {

                    if (clsSecurity.PermissionToSave(clsSecurity.UserIDLoged, iFormID, IsUpdate))
                    {
                        try
                        {
                            Cursor = Cursors.WaitCursor;
                            #region Insert
                            //Customer Order Detail                                
                            foreach (DataGridViewRow row in dgvDetail.Rows)
                            {
                                string sItemCode = "", sItemSubCategoryID = "", sItemSubCategoryID2 = "", sItemSerialNo = "", sItemSerialNo2 = "", sRemarks = "", sInquriyID = "";
                                decimal dQty = 0, dWeight = 0, dQty_DO = 0, dWeight_DO = 0, dQty_Invoice = 0, dWeight_Invoice = 0, dQty_Edit = 0, dWeight_Edit = 0;


                                dQty = clsValidate.ValidateGridValue(dgvDetail, "Quantity", row.Index, decimal.Parse("0.00"));
                                dWeight = clsValidate.ValidateGridValue(dgvDetail, "Weight", row.Index, decimal.Parse("0.00"));
                                dQty_DO = clsValidate.ValidateGridValue(dgvDetail, "QuantityDO", row.Index, decimal.Parse("0.00"));
                                dWeight_DO = clsValidate.ValidateGridValue(dgvDetail, "WeightDO", row.Index, decimal.Parse("0.00"));
                                dQty_Invoice = clsValidate.ValidateGridValue(dgvDetail, "QuantityInvoice", row.Index, decimal.Parse("0.00"));
                                dWeight_Invoice = clsValidate.ValidateGridValue(dgvDetail, "WeightInvoice", row.Index, decimal.Parse("0.00"));
                                dQty_Edit = clsValidate.ValidateGridValue(dgvDetail, "EditQuantity", row.Index, decimal.Parse("0.00"));
                                dWeight_Edit = clsValidate.ValidateGridValue(dgvDetail, "EditWeight", row.Index, decimal.Parse("0.00"));

                                sItemCode = clsValidate.ValidateGridValue(dgvDetail, "ItemCode", row.Index, "");
                                sItemSubCategoryID = clsValidate.ValidateGridTag(dgvDetail, "ItemSubCategoryID", row.Index, "default");
                                sItemSubCategoryID2 = clsValidate.ValidateGridTag(dgvDetail, "ItemSubCategoryID2", row.Index, "default");
                                sItemSerialNo = clsValidate.ValidateGridValue(dgvDetail, "ItemSerialNo", row.Index, "0");
                                sItemSerialNo2 = clsValidate.ValidateGridValue(dgvDetail, "ItemSerialNo2", row.Index, "0");
                                sInquriyID = clsValidate.ValidateGridValue(dgvDetail, "InquiryID", row.Index, "default");
                                sRemarks = clsValidate.ValidateGridValue(dgvDetail, "Remarks", row.Index, "");

                                if (sItemCode.Length > 0)
                                {
                                    if (clsAutocode.IsAutoGenerated(sFormConfigCode))
                                        txtCustomerOrderEditId.Text = clsAutocode.getAutoGeneratedCode(sFormConfigCode);

                                    if (txtCustomerOrderEditId.TextLength > 0)
                                    {

                                        tbl_sasCustomerOrder_Detail coDetail = tbl_sasCustomerOrder_Detail.Select( 0,txtCustomerOrderID.Text.Trim(),
                                            sItemCode, sItemSubCategoryID, sItemSubCategoryID2, sItemSerialNo, sItemSerialNo2);
                                        if (coDetail != null)
                                        {
                                            if (coDetail.Qty - coDetail.QtySettle_DeliveryOrder >= dQty_Edit)
                                            {
                                                //insert Edit Record
                                                tbl_sasCustomerOrder_Edit detail = new tbl_sasCustomerOrder_Edit(txtCustomerOrderEditId.Text.Trim(), sRemarks, clsSecurity.getServerDateTime(), txtCustomerOrderID.Text.Trim(),
                                                   sItemCode, sItemSubCategoryID, sItemSubCategoryID2, sItemSerialNo, sItemSerialNo2, coDetail.Qty, dQty_Edit, coDetail.Weight, dWeight_Edit, clsSecurity.UserIDLoged, clsSecurity.getServerDateTime());
                                                detail.Insert();

                                                //update Customer Order Detail
                                                coDetail.Qty += dQty_Edit;
                                                coDetail.Weight += dWeight_Edit;
                                                coDetail.Update();

                                                CheckBox chkUnitPricing = new CheckBox();
                                                chkUnitPricing.Checked = !coDetail.IsWeightCalculation;
                                                clsProcessMethods.SetSettle_CustomerOrderFrom_DeliveryOrder(txtCustomerOrderID.Text.Trim(), chkUnitPricing);
                                            }
                                        }
                                    }
                                }

                            }
                            MessageBox.Show(clsFormatter.GetMessageFrom(MessageType.SaveDone), clsFormatter.GetMessageCaption(), MessageBoxButtons.OK, MessageBoxIcon.Information);
                            #endregion
                        }
                        catch (Exception ex)
                        {
                            SEACCException.Show(ex);
                            clsValidate.WriteErrorLog("", iFormID,ex);
                        }
                        finally
                        {
                            Cursor = Cursors.Default;
                            tbl_sasCustomerOrder oldRecord = tbl_sasCustomerOrder.Select(txtCustomerOrderID.Text.Trim());
                            if (oldRecord != null)
                                FillDetails(txtCustomerOrderID.Text.Trim());
                        }
                    }
                }

            }
        }
