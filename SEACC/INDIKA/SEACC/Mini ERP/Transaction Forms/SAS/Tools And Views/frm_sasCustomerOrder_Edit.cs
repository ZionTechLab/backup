        }
        private decimal getEditValue(decimal dCoValue, decimal dDOValue, decimal dInvoiceValue)
        {
            decimal dEditValue = 0;
            try
            {
                if (dDOValue >= dInvoiceValue)
                    dEditValue = dDOValue - dCoValue;
                else
                    dEditValue = dInvoiceValue - dCoValue;
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
            return dEditValue;
        }
