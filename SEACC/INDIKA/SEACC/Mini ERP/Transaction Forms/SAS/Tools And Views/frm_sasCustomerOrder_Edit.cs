                        }
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
            return dQty;
        }
        private decimal getInvoice_Weight(string sCustomerOrderID, string sItemID, string sSubCategory1, string sSubCateogry2, string sSerial1, string sSerial2)
        {
            decimal dWeight = 0;
            try
            {
                List<tbl_sasDeliveryOrder_Detail> details = tbl_sasDeliveryOrder_Detail.SelectAllByCustomerOrder_ID(sCustomerOrderID);
