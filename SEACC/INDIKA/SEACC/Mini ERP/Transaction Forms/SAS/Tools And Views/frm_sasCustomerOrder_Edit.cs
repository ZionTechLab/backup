        private decimal getInvoice_Qty(string sCustomerOrderID, string sItemID, string sSubCategory1, string sSubCateogry2, string sSerial1, string sSerial2)
        {
            decimal dQty = 0;
            try
            {
                List<tbl_sasDeliveryOrder_Detail> details = tbl_sasDeliveryOrder_Detail.SelectAllByCustomerOrder_ID(sCustomerOrderID);
                foreach (tbl_sasDeliveryOrder_Detail detail in details)
                {
                    List<tbl_sasInvoice_Detail> invDetails = tbl_sasInvoice_Detail.SelectAllByDeliveryOrder_ID(detail.DeliveryOrder_ID);
                    foreach (tbl_sasInvoice_Detail invDetail in invDetails)
                    {
                        if (invDetail.Item_ID == sItemID && invDetail.ItemSubCategory_ID == sSubCategory1 && invDetail.ItemSubCategory2_ID == sSubCateogry2 && invDetail.ItemSerialNo == sSerial1 && invDetail.ItemSerialNo2 == sSerial2)
