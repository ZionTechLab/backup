        private void FormatForcusedCheckBox(string radioButtonName)
        {
            Color cSelectedColor = Color.FromArgb(215, 215, 0), cUnSelectedColor = Color.FromArgb(250, 244, 133);            
            foreach (Control con in flpNotes.Controls)
            {
                if (con is RadioButton)
                {
                    if (con.Name == radioButtonName)
                        con.BackColor = cSelectedColor;
                    else
                        con.BackColor = cUnSelectedColor;
                }
            }
        } 
