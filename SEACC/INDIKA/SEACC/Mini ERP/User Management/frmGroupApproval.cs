        #region BindingSource Filtering
        private void createFilterQuary(TextBox argText)
        {
            string sTemp = "";
            string sFinalQuary = "";
            //iGridCount = 1;

            if (chkCustomerName.Checked && argText.Name != "txtCustomerID")
            {
                if (sFilteQuary.Trim().Length > 0)
                    sFilteQuary += " AND CustomerName LIKE '%" + txtCustomerID.Text.Trim() + "%'";
                else
                    sFilteQuary = " CustomerName LIKE '%" + txtCustomerID.Text.Trim() + "%'";
            }
            if (chkNoteID.Checked && argText.Name != "txtNoteID")
            {
                if (sFilteQuary.Trim().Length > 0)
                    sFilteQuary += " AND NoteNumber LIKE '%" + txtNoteID.Text.Trim() + "%'";
                else
                    sFilteQuary = " NoteNumber LIKE '%" + txtNoteID.Text.Trim() + "%'";
            }
            if (chkAmount.Checked && argText.Name != "txtAmount")
            {
                if (sFilteQuary.Trim().Length > 0)
                    sFilteQuary += " AND Amount LIKE '%" + txtAmount.Text.Trim() + "%'";
                else
                    sFilteQuary = " Amount LIKE '%" + txtAmount.Text.Trim() + "%'";
            }

            if (argText.Name == "txtCustomerID")
                sTemp = " CustomerName LIKE '%" + txtCustomerID.Text.Trim() + "%'";
            if (argText.Name == "txtNoteID")
                sTemp = " NoteNumber LIKE '%" + txtNoteID.Text.Trim() + "%'";
            if (argText.Name == "txtAmount")
                sTemp = " Amount LIKE '%" + txtAmount.Text.Trim() + "%'";


            if (sTemp.Trim().Length > 0)
            {
                if (sFilteQuary.Trim().Length > 0)
                {
                    sFinalQuary = sFilteQuary + " AND " + sTemp;
                }
                else
                {
                    sFinalQuary = sTemp;
                }
            }
            source.Filter = "";
            if (sFinalQuary.Trim().Length > 0)
                source.Filter = sFinalQuary;
            else
                source.Filter = sTemp;
        }
