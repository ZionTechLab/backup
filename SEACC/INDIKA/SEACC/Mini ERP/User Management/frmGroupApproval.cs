                sColName = dgvDetail.Columns[e.ColumnIndex].Name;

            if (sColName == "CustomerName" || sColName == "PDCheques" || sColName == "CrediteBalance" || sColName == "RCOutstandings")
            {
                frm_sasViewerCustomer frm = new frm_sasViewerCustomer();
                frm.glbCustomerID = dgvDetail["CustomerID", e.RowIndex].Value.ToString();
                frm.ShowDialog();
            }
            else if (sColName == "NoteNumber" || sColName == "Amount")
            {
               DisplayNoteView(dgvDetail["NoteNumber", e.RowIndex].Value.ToString());
            }
            else if (sColName == "ApprovalStatus")
            {
                Form frmhelpsearch = new frmSearchMaster();
                //clsSearch.passValue_Section();
                frmSearchMaster.s_TableName = "tbl_zBatchApprovalStatus";
                frmSearchMaster.s_Columns = " batchApprovalStatus_ID Status_ID, batchApprovalStatus StatusName ";
                frmSearchMaster.i_ColumnWidth = new int[] { 100, 250 };
                frmSearchMaster.s_Criteria = "batchApprovalStatus_ID != 'default'";

                frmhelpsearch.ShowDialog();
                if (frmSearchMaster.s_SearchText.Length > 0)
                    dgvDetail["ApprovalStatus", e.RowIndex].Value = frmSearchMaster.s_SearchText;
                if (frmSearchMaster.s_SearchID.Length > 0)
                    dgvDetail["ApprovalStatusID", e.RowIndex].Tag = frmSearchMaster.s_SearchID;
            }
        }
