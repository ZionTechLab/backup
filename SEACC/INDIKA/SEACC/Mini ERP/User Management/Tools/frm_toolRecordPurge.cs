        private bool DeleteCheque(string sChequeRegisterID)
        {
            bool bValue = true;
            try
            {                
                clsHelpMethods_Local.RemoveSattlementsFrom_ChequeID(sChequeRegisterID);

                //tbl_bpsChequeReconciliation_Detail
                foreach (tbl_bpsChequeReconciliation_Detail oChqReq in tbl_bpsChequeReconciliation_Detail.SelectAllByChequeRegister_ID(sChequeRegisterID))
                {
                    if (oChqReq != null)
                        oChqReq.Delete();
                }
                //tbl_bpsChequeDeposit_Detail
                foreach (tbl_bpsChequeDeposit_Detail oChqDep in tbl_bpsChequeDeposit_Detail.SelectAllByChequeRegister_ID(sChequeRegisterID))
                {
                    if (oChqDep != null)
                        oChqDep.Delete();
                }

                //tbl_bpsChequeReIssue_Detail
                foreach (tbl_bpsChequeReIssue_Detail oChqReIss in tbl_bpsChequeReIssue_Detail.SelectAllByChequeRegister_ID(sChequeRegisterID))
                {
                    if (oChqReIss != null)
                        oChqReIss.Delete();
                }

                //tbl_bpsChequeRegister
                tbl_bpsChequeRegister oChqRegister = tbl_bpsChequeRegister.Select(sChequeRegisterID);
                if (oChqRegister != null && oChqRegister.ChequeRegister_ID != "default")
                    oChqRegister.Delete();               
            }
            catch (Exception ex)
            {
                bValue = false;
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
            return bValue;
        }
