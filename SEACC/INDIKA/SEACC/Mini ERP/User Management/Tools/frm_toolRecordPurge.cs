        #region Fill Datagrid
        private void Fill_Datagrid(int iRow, int iLineNo, string sProcessNote, string sProcessNoteID, string sTransactionID, string sTransactionDate, bool bIsBackup, bool bIsPurge, string sCustomerID)
        {
            try
            {
                foreach (DataGridViewRow row in dgvDetail.Rows)
                {
                    string sTmpTransactionID = "", sTmpTransactionName = "";
                    sTmpTransactionName = clsValidate.ValidateGridValue(dgvDetail, "TransactionName", row.Index, "default");
                    sTmpTransactionID = clsValidate.ValidateGridTag(dgvDetail, "TransactionID", row.Index, "default");
                    if (sTmpTransactionID == sTransactionID && sTmpTransactionName == sProcessNote)
                    {
                        dgvDetail.Rows.RemoveAt(iRow);
                    }
                }

                dgvDetail["LineNo", iRow].Value = iLineNo.ToString();
                dgvDetail["TransactionName", iRow].Value = sProcessNote;
                dgvDetail["TransactionName", iRow].Tag = sProcessNoteID;
                dgvDetail["TransactionID", iRow].Value = sTransactionID;
                dgvDetail["TransactionDate", iRow].Value = sTransactionDate;
                dgvDetail["IsBackUp", iRow].Value = bIsBackup;
                dgvDetail["IsPurged", iRow].Value = bIsPurge;
                dgvDetail["CustomerID", iRow].Value = sCustomerID;

            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
