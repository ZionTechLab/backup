        #region Refresh Grid
        private void RefreshGrid(string sPurgeID)
        {
            try
            {
                int iRow;
                dgvDetail.Rows.Clear();
                tbl_securityPurge oPurge = tbl_securityPurge.Select(sPurgeID);
                if (oPurge != null && oPurge.Purge_ID != "default")
                {
                    List<tbl_securityPurge_Detail> details = tbl_securityPurge_Detail.SelectAllByPurge_ID(oPurge.Purge_ID);
                    foreach (tbl_securityPurge_Detail detail in details)
                    {
                        if (detail.Purge_ID.Trim() != "default")
                        {
                            dgvDetail.Rows.Add();
                            iRow = dgvDetail.Rows.Count - 1;
                            dgvDetail["LineNo", iRow].Value = detail.Line_No.ToString();
                            dgvDetail["TransactionName", iRow].Value = clsGenaralName.getName_ProcessNote(detail.ProcessNote_ID);
                            dgvDetail["TransactionID", iRow].Value = detail.Transaction_ID;
                            dgvDetail["IsPurged", iRow].Value = detail.IsPurgeEnd;
                            dgvDetail["IsPurged", iRow].Value = detail.IsPurgeEnd;
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                clsValidate.WriteErrorLog("", iFormID,ex);
                SEACCException.Show(ex);
            }
        }
