import { useState, useEffect, useCallback } from "react";
import * as Yup from "yup";
import { useParams, useNavigate } from "react-router-dom";
import { useFormikBuilder, FieldsRenderer } from "../../../../helpers/formikBuilder";
import MeridianPage from "../../MeridianPage";
import companiesService from "./service";
import UserServiceInstance from "../../../UserMaster/UserService";
import MessageBoxService from "../../../../services/MessageBoxService";
import Modal from "../../../../components/Modal";
import { DataTable } from "../../../../components/DataTable";
import ApiService from './service';


import config from "../../../../config/config";




export default function AddCompany() {
  const { id }   = useParams();
  const navigate = useNavigate();
  const isEdit   = Boolean(id);
  const [uiData, setUiData] = useState({ loading: false, success: false, error: '', data: {} });


  const fields = {
  companyId:       { name: "companyId",       type: "text",   placeholder: "Company ID",         initialValue: "<Auto-generated>", className: "col-md-4", disabled: true },
  companyCode:     { name: "companyCode",     type: "text",   placeholder: "Company Code",       initialValue: "", className: "col-md-4", validation: Yup.string().required("Code is required") },
  companyName:     { name: "companyName",     type: "text",   placeholder: "Legal Entity Name",  initialValue: "", className: "col-md-8", validation: Yup.string().required("Name is required") },
  tenantId:   { name: "tenantId",   type: "select", placeholder: "Select Tenant",      initialValue: "", className: "col-md-4", validation: Yup.string().required("Tenant is required"),   dataBinding: { data:  uiData?.data?.tenants    ?? [], keyField: "tenantId",     valueField: "tenantName" } },
  groupId:    { name: "groupId",    type: "select", placeholder: "Select Group",       initialValue: "", className: "col-md-8", validation: Yup.string().required("Group is required"),    dataBinding: { data:  uiData?.data?.groups    ?? [], keyField: "groupId",      valueField: "groupName" } },
  country:  { name: "country",  type: "select", placeholder: "Select Country",     initialValue: "", className: "col-md-4", validation: Yup.string().required("Country is required"),  dataBinding: { data:  uiData?.data?.countries  ?? [], keyField: "id",           valueField: "description" } },
  baseCurrencyCode: { name: "baseCurrencyCode", type: "select", placeholder: "Base Currency",      initialValue: "", className: "col-md-4", validation: Yup.string().required("Currency is required"), dataBinding: { data:  uiData?.data?.currencies  ?? [], keyField: "currencyCode", valueField: "label" } },
};







  useEffect(() => {

      const fetchUi = async () => {
      setUiData(prev => ({ ...prev, loading: true, error: '', data: {} }));
      const data = await ApiService.getUi();
      setUiData(prev => ({ ...prev, ...data , loading: false }));
    };
    fetchUi();

    if (id) {
      const fetchTxn = async () => {
        const response = await ApiService.get(id);
        if (response.success) {
          if (response.data) {
            formik.setValues({ ...response.data });
          }
        }
      };
      fetchTxn();

    // if (!isEdit) return;
    // companiesService.get(id).then(({ success, data }) => {
    //   if (success && data) {
    //     formik.setValues({
    //       code:       data.code       ?? "",
    //       name:       data.name       ?? "",
    //       group:      data.group      ?? "",
    //       country:    data.country    ?? "",
    //       currency:   data.currency   ?? "",
    //       fiscalYear: data.fiscalYear ?? "",
    //       role:       data.role       ?? "",
    //     });
    //   }
    // });
}
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const handleSubmit = async (values, { resetForm }) => {
    const param = {
      header: { ...values, companyId: id ? id : 0 },
      isUpdate: id ? true : false
    };
    const response = await ApiService.update({ ...param });
    const { success, data } = response;
    if (success) {
      MessageBoxService.show({
        message: "Company saved successfully!",
        type: "success",
        onClose: () => {
          if (config.features.returnToListAfterSave) {
            navigate("/settings/companies");
          } else if (!id && data?.companyId) {
            navigate(`/settings/companies/edit/${data.companyId}`);
          } else if (!id) {
            resetForm();
          }
        },
      });
    }
  };

    const formik = useFormikBuilder(fields, handleSubmit);

  const handleDelete = async () => {
    if (!isEdit) return;
    const confirmed = await MessageBoxService.confirmAsync({
      message: "Delete this company? This cannot be undone.",
      type: "danger",
      confirmText: "Delete",
      cancelText: "Cancel",
    });
    if (!confirmed) return;
    const response = await companiesService.delete(id);
    if (response.success) {
      MessageBoxService.show({
        message: "Company deleted.",
        type: "success",
        onClose: () => navigate("/settings/companies"),
      });
    }
  };

  // --- Users with Access ---
  const [memberUsers, setMemberUsers] = useState([]);
  const [memberLoading, setMemberLoading] = useState(false);
  const [showAddModal, setShowAddModal] = useState(false);
  const [allUsers, setAllUsers] = useState([]);
  const [selectedUserId, setSelectedUserId] = useState("");

  const loadMembers = useCallback(async () => {
    if (!id) return;
    setMemberLoading(true);
    const { success, data } = await companiesService.listUsers(id);
    if (success) setMemberUsers(data || []);
    setMemberLoading(false);
  }, [id]);

  useEffect(() => {
    loadMembers();
  }, [loadMembers]);

  const openAddModal = async () => {
    const { success, data } = await UserServiceInstance.getAll();
    if (success) {
      const existingIds = new Set(memberUsers.map((m) => m.userId));
      const available = (data || []).filter((u) => !existingIds.has(u.userId));
      setAllUsers(available);
      setSelectedUserId(available[0]?.userId ?? "");
      setShowAddModal(true);
    }
  };

  const handleAddUser = async () => {
    if (!selectedUserId) return;
    const { success } = await companiesService.addUser({ companyId: id, userId: selectedUserId });
    if (success) {
      MessageBoxService.show({ message: "User added to company.", type: "success" });
      setShowAddModal(false);
      loadMembers();
    }
  };

  const handleRemoveUser = async (row) => {
    const msg = `Remove ${row.fullName} from this company?`;
    const confirmed = await MessageBoxService.confirmAsync({ message: msg, type: "danger", confirmText: "Remove", cancelText: "Cancel" });
    if (!confirmed) return;
    const { success } = await companiesService.removeUser(row.id);
    if (success) {
      MessageBoxService.show({ message: `${row.fullName} removed.`, type: "success" });
      loadMembers();
    }
  };

  const handleSetDefault = async (row) => {
    const msg = `Make ${row.fullName}'s default company?`;
    const confirmed = await MessageBoxService.confirmAsync({ message: msg, type: "warning", confirmText: "Yes", cancelText: "Cancel" });
    if (!confirmed) return;
    const { success } = await companiesService.setDefaultUser(row.id);
    if (success) {
      MessageBoxService.show({ message: `Default company set for ${row.fullName}.`, type: "success" });
      loadMembers();
    }
  };

  const memberColumns = [
    { header: "User", field: "fullName" },
    { header: "Email", field: "email" },
    { header: "Status", field: "isActive", render: (r) => <span className={`badge ${r.isActive ? 'bg-success' : 'bg-secondary'}`}>{r.isActive ? 'Active' : 'Inactive'}</span> },
    { header: "Default", field: "isDefault", render: (r) => r.isDefault ? <span className="badge bg-primary">Default</span> : <span className="text-muted">-</span> },
    {
      header: "Actions", field: "actions", isAction: true,
      render: (r) => (
        <div className="d-flex gap-1">
          {!r.isDefault && (
            <button type="button" className="btn btn-sm btn-outline-primary" title="Make default" onClick={(e) => { e.stopPropagation(); handleSetDefault(r); }}>
              <i className="bi bi-star" />
            </button>
          )}
          <button type="button" className="btn btn-sm btn-outline-danger" title="Remove" onClick={(e) => { e.stopPropagation(); handleRemoveUser(r); }}>
            <i className="bi bi-person-x" />
          </button>
        </div>
      ),
    },
  ];

  return (
    <MeridianPage
      title={isEdit ? "Edit Company" : "New Company"}
      backTo="/settings/companies"
      cardClass="ml-form-card"
      actions={
        <>
          {isEdit && (
            <button
              type="button"
              className="ml-btn-ghost ml-btn-danger-ghost ml-fab-1"
              onClick={handleDelete}
            >
              <i className="bi bi-trash" aria-hidden="true" />
              Delete
            </button>
          )}
          <button
            type="submit"
            form="company-form"
            className="ml-btn-action ml-fab"
            disabled={formik.isSubmitting}
          >
            {formik.isSubmitting
              ? <span className="ml-spinner" aria-hidden="true" />
              : <i className="bi bi-check-lg" aria-hidden="true" />}
            {isEdit ? "Save Changes" : "Create Company"}
          </button>
        </>
      }
    >
      <form id="company-form" onSubmit={formik.handleSubmit}>
        <div className="ml-form-section">
          <div className="ml-form-section-label">Identity</div>
          <div className="row g-3">
            <FieldsRenderer fields={{ companyId: fields.companyId, companyCode: fields.companyCode, companyName: fields.companyName }} formik={formik} />
          </div>
        </div>

        <div className="ml-form-section">
          <div className="ml-form-section-label">Classification</div>
          <div className="row g-3">
            <FieldsRenderer fields={{ tenantId: fields.tenantId, groupId: fields.groupId, country: fields.country, baseCurrencyCode: fields.baseCurrencyCode }} formik={formik} />
          </div>
        </div>
      </form>

      {isEdit && (
        <div className="ml-form-section mt-4">
          <div className="d-flex justify-content-between align-items-center mb-3">
            <div className="ml-form-section-label m-0">Users with Access</div>
            <button type="button" className="btn btn-outline-primary btn-sm" onClick={openAddModal}>
              <i className="bi bi-plus-lg" aria-hidden="true" /> Add User
            </button>
          </div>
          <DataTable
            data={memberUsers}
            columns={memberColumns}
            loading={memberLoading}
            pageSize={10}
            features={{ csvExport: false, columnVisibility: false, cardView: false }}
          />
        </div>
      )}

      <Modal show={showAddModal} onClose={() => setShowAddModal(false)} title="Add User to Company">
        <div className="mb-3">
          <label className="form-label">Select User</label>
          <select
            className="form-select"
            value={selectedUserId}
            onChange={(e) => setSelectedUserId(e.target.value)}
          >
            {allUsers.length === 0 && <option value="">No users available</option>}
            {allUsers.map((u) => (
              <option key={u.userId} value={u.userId}>{u.fullName} ({u.userName})</option>
            ))}
          </select>
        </div>
        <div className="d-flex justify-content-end gap-2">
          <button type="button" className="btn btn-secondary" onClick={() => setShowAddModal(false)}>Cancel</button>
          <button type="button" className="btn btn-primary" onClick={handleAddUser} disabled={!selectedUserId}>Add</button>
        </div>
      </Modal>
    </MeridianPage>
  );
}
